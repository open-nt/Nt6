/*!
    \class QInputMethod
    \inmodule NtGui
    \since 6.0
    \brief The QInputMethod class is the input method of the platform, such as an on-screen keyboard.

    QGuiApplication::inputMethod() returns it. show() and hide() ask for the input panel:

    \code
    QGuiApplication::inputMethod()->hide(); // done typing
    \endcode

    \differences
    Nt has no input methods, and only the android platform has an input panel: elsewhere show() and hide() only set isVisible() and emit visibleChanged(),
    the keyboard rectangle is empty, and the locale is that of QLocale().
    \enddifferences
*/

/*!
    \enum QInputMethod::Action

    What invokeAction() does.

    \value Click A click on the text being composed.
    \value ContextMenu A context menu on it.
*/

