#include <QtWidgets/qfontcombobox.h>

#include "gui/qfontengine_p.h"

/*!
    \class QFontComboBox
    \brief The QFontComboBox class lets the user choose a font family from a list.

    The list has the generic families Sans Serif, Serif and Monospace, then the families that fontconfig finds:

    \code
    auto *fonts = new QFontComboBox(toolBar);
    connect(fonts, &QFontComboBox::currentFontChanged, editor, &QWidget::setFont);
    \endcode

    \differences
    The families are shown in the font of the combo box, not in their own font. The font filters are recorded but do
    not filter, and there is no \c writingSystem().
    \enddifferences

    \sa QFontDialog, QComboBox
*/

/*!
    \enum QFontComboBox::FontFilter

    Which families the list shows; recorded only. FontFilters is a typedef for \c{QFlags<FontFilter>}.

    \value AllFonts All of them.
    \value ScalableFonts Scalable fonts.
    \value NonScalableFonts Bitmap fonts.
    \value MonospacedFonts Fonts whose characters have one width.
    \value ProportionalFonts Fonts whose characters have their own widths.
*/

/*!
    Constructs a font combo box with the given \a parent. The current family is that of the application font, or
    the first one.
*/
QFontComboBox::QFontComboBox(QWidget *parent) : QComboBox(parent) {
    QStringList families = {QStringLiteral("Sans Serif"), QStringLiteral("Serif"), QStringLiteral("Monospace")};
    for (const QString &family : QFontEngine::families())
        if (!families.contains(family))
            families.append(family);
    addItems(families);
    const int index = findText(QFont().family());
    setCurrentIndex(index >= 0 ? index : 0);
    QObject::connect(this, &QComboBox::currentIndexChanged, this, [this] { emit currentFontChanged(currentFont()); });
}

/*!
    Destroys the combo box.
*/
QFontComboBox::~QFontComboBox() = default;

/*!
    \fn void QFontComboBox::setFontFilters(FontFilters filters)

    Sets the families that the list shows to \a filters; recorded only.
*/

/*!
    \fn QFontComboBox::FontFilters QFontComboBox::fontFilters() const

    Returns the families that the list shows, AllFonts by default.
*/

/*!
    Returns a font of the current family.

    \sa setCurrentFont()
*/
QFont QFontComboBox::currentFont() const {
    QFont font;
    font.setFamily(currentText());
    return font;
}

/*!
    Makes the family of \a font current. A family that is not in the list is added to it.

    \sa currentFont()
*/
void QFontComboBox::setCurrentFont(const QFont &font) {
    int index = findText(font.family());
    if (index < 0 && !font.family().isEmpty()) {
        addItem(font.family());
        index = count() - 1;
    }
    if (index >= 0)
        setCurrentIndex(index);
}

