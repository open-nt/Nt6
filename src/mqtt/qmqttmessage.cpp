#include <QtMqtt/qmqttmessage.h>

/*!
    \class QMqttMessage
    \brief The QMqttMessage class is a message that a subscription received.
    \since 6.0

    QMqttSubscription::messageReceived() hands each message over with its topic, payload and the
    flags it arrived with.

    \differences
    Objects of this class are plain values, not implicitly shared. There are no publish
    properties, which come with MQTT 5.
    \enddifferences

    \sa QMqttSubscription
*/

/*!
    \fn QMqttMessage::QMqttMessage()

    Constructs an empty message.
*/

QMqttMessage::QMqttMessage(const QMqttTopicName &topic, const QByteArray &payload, quint16 id, quint8 qos,
                           bool duplicate, bool retain)
    : m_topic(topic), m_payload(payload), m_id(id), m_qos(qos), m_duplicate(duplicate), m_retain(retain) {}

/*!
    Returns the payload of the message.
*/
const QByteArray &QMqttMessage::payload() const { return m_payload; }

/*!
    Returns the QoS the message arrived with.
*/
quint8 QMqttMessage::qos() const { return m_qos; }

/*!
    Returns the packet identifier the message arrived with; 0 for QoS 0.
*/
quint16 QMqttMessage::id() const { return m_id; }

/*!
    Returns the topic the message was published to.
*/
QMqttTopicName QMqttMessage::topic() const { return m_topic; }

/*!
    Returns whether the broker marked the message as sent again.
*/
bool QMqttMessage::duplicate() const { return m_duplicate; }

/*!
    Returns whether the message was retained by the broker, which delivers it on subscribing.
*/
bool QMqttMessage::retain() const { return m_retain; }

