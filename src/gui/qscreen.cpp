#include <QtGui/qscreen.h>

#include "qpa/qplatformscreen_p.h"

/*!
    \class QScreen
    \brief The QScreen class is used to query screen properties.

    A screen is a monitor. QGuiApplication::primaryScreen() returns the main one
    and QGuiApplication::screens() all of them. Windows are created on a screen.

    \differences
    Only the geometry, depth and resolution are available. There is no
    orientation, refresh rate, manufacturer, virtual siblings or
    \c grabWindow(). The device pixel ratio is always 1.
    \enddifferences

    \sa QGuiApplication, QWindow
*/

QScreen::QScreen(QPlatformScreen *screen) : m_platform(screen) { screen->m_screen = this; }

/*!
    Destroys the screen object.
*/
QScreen::~QScreen() {
    if (m_platform)
        m_platform->m_screen = nullptr;
}

/*!
    Returns the name of the screen, such as \c{"DP-1"}.
*/
QString QScreen::name() const { return m_platform->name(); }

/*!
    Returns the number of bits per pixel.
*/
int QScreen::depth() const { return m_platform->depth(); }

/*!
    Returns the size of the screen in pixels.

    \sa geometry()
*/
QSize QScreen::size() const { return m_platform->geometry().size(); }

/*!
    Returns the geometry of the screen in pixels.

    \sa size(), availableGeometry()
*/
QRect QScreen::geometry() const { return m_platform->geometry(); }

/*!
    Returns the part of the screen that windows can use, which excludes
    panels and docks when the platform reports them.

    \sa geometry()
*/
QRect QScreen::availableGeometry() const { return m_platform->availableGeometry(); }

/*!
    Returns the size of the screen in millimeters.
*/
QSizeF QScreen::physicalSize() const { return m_platform->physicalSize(); }

/*!
    Returns the number of logical dots per inch in the horizontal direction.

    \sa logicalDotsPerInch()
*/
qreal QScreen::logicalDotsPerInchX() const { return m_platform->logicalDpiX(); }

/*!
    Returns the number of logical dots per inch in the vertical direction.

    \sa logicalDotsPerInch()
*/
qreal QScreen::logicalDotsPerInchY() const { return m_platform->logicalDpiY(); }

/*!
    Returns the average of the horizontal and vertical logical dots per inch.
*/
qreal QScreen::logicalDotsPerInch() const { return (logicalDotsPerInchX() + logicalDotsPerInchY()) / 2.0; }

/*!
    Returns the number of physical dots per inch, computed from the size in
    pixels and in millimeters.
*/
qreal QScreen::physicalDotsPerInch() const {
    const QSizeF mm = physicalSize();
    if (mm.width() <= 0.0 || mm.height() <= 0.0)
        return logicalDotsPerInch();
    const QSize px = size();
    return (px.width() / mm.width() + px.height() / mm.height()) * 25.4 / 2.0;
}

/*!
    Returns the number of pixels of the screen that one unit of window coordinates covers. It is
    1 on an ordinary screen and 2 on one with twice the usual density. The xcb platform takes it
    from the \c Xft.dpi resource, or from the \c QT_SCALE_FACTOR environment variable.

    A QWindow, a QScreen and a QWidget measure in these units, whereas a QImage counts pixels.
*/
qreal QScreen::devicePixelRatio() const { return m_platform->devicePixelRatio(); }

