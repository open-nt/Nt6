#include <QtGui/qpaintdevicewindow.h>

#include <QtGui/qbackingstore.h>
#include <QtGui/qevent.h>
#include <QtGui/qpaintengine.h>

/*!
    \class QPaintDeviceWindow
    \brief The QPaintDeviceWindow class is the base class for windows that are paint devices.

    The window owns a backing store. When the window needs painting, which
    is when it is exposed or when update() asks for it, it calls paintEvent()
    with the region to paint. Paint on the window with a QPainter:

    \code
    void MyWindow::paintEvent(QPaintEvent *event)
    {
        QPainter painter(this);
        painter.fillRect(event->rect(), Qt::white);
    }
    \endcode

    \differences
    The window always paints in software, into a QImage. Qt's class is the base
    of QOpenGLWindow as well. Nt does not call paintEvent() before the window
    is exposed.
    \enddifferences

    \sa QRasterWindow, QWindow, QBackingStore
*/

/*!
    Constructs a paint device window. The window is not visible.
*/
QPaintDeviceWindow::QPaintDeviceWindow() = default;

/*!
    Destroys the window.
*/
QPaintDeviceWindow::~QPaintDeviceWindow() = default;

/*!
    \fn int QPaintDeviceWindow::width() const

    Returns the width of the window in pixels.
*/

/*!
    \fn int QPaintDeviceWindow::height() const

    Returns the height of the window in pixels.
*/

/*!
    \fn qreal QPaintDeviceWindow::devicePixelRatio() const

    Returns the device pixel ratio of the window, as QWindow::devicePixelRatio() does.
*/

/*!
    \reimp
*/
QPaintEngine *QPaintDeviceWindow::paintEngine() const {
    if (!m_store)
        return nullptr;
    QPaintDevice *device = m_store->paintDevice();
    return device ? device->paintEngine() : nullptr;
}

/*!
    \reimp
*/
QPaintDevice *QPaintDeviceWindow::redirected(QPoint *offset) const {
    if (!m_store)
        return nullptr;
    (void)offset;
    return m_store->paintDevice();
}

/*!
    \reimp
*/
int QPaintDeviceWindow::metric(PaintDeviceMetric metric) const {
    switch (metric) {
    case PdmWidth:
        return width();
    case PdmHeight:
        return height();
    case PdmDevicePixelRatio:
        return static_cast<int>(QWindow::devicePixelRatio());
    case PdmDevicePixelRatioScaled:
        return qRound(QWindow::devicePixelRatio() * 65536.0);
    default:
        return QPaintDevice::metric(metric);
    }
}

/*!
    Marks the whole window as needing a repaint. The paint event is delivered
    from the event loop.

    \sa paintEvent()
*/
void QPaintDeviceWindow::update() { update(QRect(0, 0, width(), height())); }

/*!
    \overload

    Marks \a rect as needing a repaint.
*/
void QPaintDeviceWindow::update(const QRect &rect) { update(QRegion(rect)); }

/*!
    \overload

    Marks \a region as needing a repaint.
*/
void QPaintDeviceWindow::update(const QRegion &region) {
    m_dirty += region;
    requestUpdate();
}

/*!
    Handles the paint event \a event: paint its region of the window. Use a
    QPainter on the window. The default does nothing.

    \sa update()
*/
void QPaintDeviceWindow::paintEvent(QPaintEvent *event) { (void)event; }

void QPaintDeviceWindow::doFlush() {
    if (!isExposed()) {
        m_dirty = QRegion();
        return;
    }
    const QRegion region = m_dirty.intersected(QRect(0, 0, width(), height()));
    m_dirty = QRegion();
    if (region.isEmpty() || width() <= 0 || height() <= 0)
        return;
    if (!m_store)
        m_store = std::make_unique<QBackingStore>(this);
    if (m_store->size() != size())
        m_store->resize(size());
    m_store->beginPaint(region);
    QPaintEvent paint(region);
    paintEvent(&paint);
    m_store->endPaint();
    m_store->flush(region);
}

/*!
    \reimp
*/
void QPaintDeviceWindow::exposeEvent(QExposeEvent *event) {
    if (isExposed()) {
        m_dirty += event->region();
        doFlush();
    }
}

/*!
    \reimp
*/
void QPaintDeviceWindow::resizeEvent(QResizeEvent *event) {
    (void)event;
    update();
}

/*!
    \reimp
*/
bool QPaintDeviceWindow::event(QEvent *event) {
    if (event->type() == QEvent::UpdateRequest) {
        QWindow::event(event);
        doFlush();
        return true;
    }
    return QWindow::event(event);
}

