#include <QtWidgets/qsplashscreen.h>

#include <QtCore/qcoreapplication.h>
#include <QtGui/qevent.h>
#include <QtGui/qguiapplication.h>
#include <QtGui/qpainter.h>
#include <QtGui/qscreen.h>

/*!
    \class QSplashScreen
    \brief The QSplashScreen class shows a picture while the application starts.

    A splash screen is a frameless window in the middle of the screen with a pixmap and a message. Show it before the
    main window is made, and let it close when the main window shows:

    \code
    QPixmap picture(400, 200);
    picture.fill(Qt::darkCyan);
    QSplashScreen splash(picture);
    splash.show();
    splash.showMessage("Loading plugins...", Qt::AlignBottom | Qt::AlignHCenter, Qt::white);
    loadPlugins();
    MainWindow window;
    window.show();
    splash.finish(&window);
    \endcode

    The message is drawn over the pixmap; reimplement drawContents() to draw more. showMessage() repaints at once, so
    the message is seen even while the application is busy. A click closes the splash screen.

    \differences
    There is no \c QSplashScreen(QScreen *) constructor, and pixmaps cannot be loaded from files in Nt, so the pixmap is
    painted by the application.
    \enddifferences

    \sa QPixmap
*/

/*!
    Constructs a splash screen with the given \a pixmap and window flags \a f. It is a frameless window that stays on
    top.
*/
QSplashScreen::QSplashScreen(const QPixmap &pixmap, Qt::WindowFlags f)
    : QWidget(nullptr, Qt::SplashScreen | Qt::FramelessWindowHint | Qt::WindowStaysOnTopHint | f) {
    setPixmap(pixmap);
}

/*!
    Destroys the splash screen.
*/
QSplashScreen::~QSplashScreen() {
    if (m_waitFor)
        m_waitFor->removeEventFilter(this);
}

/*!
    Sets the pixmap of the splash screen to \a pixmap; the window takes its size and moves to the middle of the screen.

    \sa pixmap()
*/
void QSplashScreen::setPixmap(const QPixmap &pixmap) {
    m_pixmap = pixmap;
    const QSize size = sizeHint();
    QRect area(QPoint(0, 0), size);
    if (QScreen *screen = QGuiApplication::primaryScreen())
        area.moveCenter(screen->geometry().center());
    setGeometry(area);
    update();
}

/*!
    \fn QPixmap QSplashScreen::pixmap() const

    Returns the pixmap of the splash screen.
*/

/*!
    Closes the splash screen when \a mainWin is shown, or at once if it is shown already.
*/
void QSplashScreen::finish(QWidget *mainWin) {
    if (!mainWin || mainWin->isVisible()) {
        close();
        return;
    }
    m_waitFor = mainWin;
    mainWin->installEventFilter(this);
}

/*!
    \fn QString QSplashScreen::message() const

    Returns the message that is shown, or an empty string.
*/

/*!
    \reimp
*/
QSize QSplashScreen::sizeHint() const { return m_pixmap.isNull() ? QSize(300, 150) : m_pixmap.size(); }

/*!
    Shows \a message over the pixmap, placed by \a alignment, in \a color, and repaints at once.

    \sa clearMessage(), messageChanged()
*/
void QSplashScreen::showMessage(const QString &message, int alignment, const QColor &color) {
    m_message = message;
    m_alignment = alignment;
    m_color = color;
    emit messageChanged(message);
    repaint();
}

/*!
    Removes the message.
*/
void QSplashScreen::clearMessage() {
    m_message.clear();
    emit messageChanged(QString());
    repaint();
}

/*!
    \reimp

    The splash screen closes when the window given to finish() is shown.
*/
bool QSplashScreen::eventFilter(QObject *watched, QEvent *event) {
    if (watched == m_waitFor && event->type() == QEvent::Show) {
        m_waitFor->removeEventFilter(this);
        m_waitFor = nullptr;
        close();
    }
    return false;
}

/*!
    Draws the message with \a painter. Reimplement it to draw more over the pixmap.
*/
void QSplashScreen::drawContents(QPainter *painter) {
    painter->setPen(m_color);
    painter->drawText(rect().adjusted(5, 5, -5, -5), m_alignment | Qt::TextWordWrap, m_message);
}

/*!
    \reimp
*/
void QSplashScreen::paintEvent(QPaintEvent *event) {
    (void)event;
    QPainter painter(this);
    if (!m_pixmap.isNull())
        painter.drawPixmap(0, 0, m_pixmap);
    drawContents(&painter);
}

/*!
    \reimp

    A click hides the splash screen.
*/
void QSplashScreen::mousePressEvent(QMouseEvent *event) {
    hide();
    event->accept();
}

