#include <QtWidgets/qcheckbox.h>

#include <QtGui/qpainter.h>
#include <QtWidgets/qstyle.h>
#include <QtWidgets/qstyleoption.h>

/*!
    \class QCheckBox
    \brief The QCheckBox class provides a checkbox with a text label.

    A check box is a checkable button that shows its state in an indicator next to the text. Connect to
    toggled():

    \code
    QCheckBox *box = new QCheckBox("Remember me", window);
    box->setChecked(true);
    \endcode

    Check boxes: unchecked, checked, with the keyboard focus, and disabled.

    \image widgets/qcheckbox.png QCheckBox in the light color scheme

    \differences
    There are no tristate check boxes and no \c stateChanged() signal or \c checkState(); use toggled() and isChecked().
    \enddifferences

    \sa QAbstractButton, QPushButton
*/

/*!
    Constructs a check box with no text and the given \a parent.
*/
QCheckBox::QCheckBox(QWidget *parent) : QAbstractButton(parent) {
    setCheckable(true);
    setSizePolicy(QSizePolicy::Minimum, QSizePolicy::Fixed);
}

/*!
    Constructs a check box that shows \a text, with the given \a parent.
*/
QCheckBox::QCheckBox(const QString &text, QWidget *parent) : QAbstractButton(parent) {
    setCheckable(true);
    setSizePolicy(QSizePolicy::Minimum, QSizePolicy::Fixed);
    setText(text);
}

/*!
    Destroys the check box.
*/
QCheckBox::~QCheckBox() = default;

/*!
    \reimp
*/
QSize QCheckBox::sizeHint() const {
    const QSize text = fontMetrics().size(Qt::TextSingleLine, this->text());
    QStyleOptionButton option;
    option.initFrom(this);
    option.text = this->text();
    return style()->sizeFromContents(QStyle::CT_CheckBox, &option, text, this);
}

/*!
    \reimp
*/
bool QCheckBox::hitButton(const QPoint &pos) const {
    const QSize hint = sizeHint();
    return QRect(0, 0, std::min(width(), hint.width()), height()).contains(pos);
}

/*!
    \reimp
*/
void QCheckBox::paintEvent(QPaintEvent *event) {
    (void)event;
    QPainter painter(this);
    painter.setFont(font());
    QStyleOptionButton option;
    initStyleOption(&option);
    style()->drawControl(QStyle::CE_CheckBox, &option, &painter, this);
}

/*!
    \since 6.0

    Fills \a option with the state of the check box, for the style to draw it.
*/
void QCheckBox::initStyleOption(QStyleOptionButton *option) const {
    if (!option)
        return;
    option->initFrom(this);
    option->text = text();
    option->icon = icon();
    option->iconSize = iconSize();
    option->state |= isDown() ? QStyle::State_Sunken : QStyle::State_Raised;
    if (m_partial)
        option->state |= QStyle::State_NoChange;
    else
        option->state |= isChecked() ? QStyle::State_On : QStyle::State_Off;
}

/*!
    \fn bool QCheckBox::isTristate() const
    \since 6.0

    Returns whether the check box has a third, partially checked state. The default is \c false.
*/

/*!
    \fn void QCheckBox::setTristate(bool y)
    \since 6.0

    Gives the check box a partially checked state if \a y is \c true: a click then goes from unchecked to partially
    checked to checked.
*/

/*!
    \since 6.0

    Returns the check state: Qt::PartiallyChecked, Qt::Checked or Qt::Unchecked.
*/
Qt::CheckState QCheckBox::checkState() const {
    if (m_partial)
        return Qt::PartiallyChecked;
    return isChecked() ? Qt::Checked : Qt::Unchecked;
}

/*!
    \since 6.0

    Sets the check state to \a state, and emits checkStateChanged() and stateChanged() if it changes.
    Qt::PartiallyChecked makes the check box tristate.
*/
void QCheckBox::setCheckState(Qt::CheckState state) {
    if (state == Qt::PartiallyChecked)
        m_tristate = true;
    m_partial = state == Qt::PartiallyChecked;
    m_blockRefresh = true;
    setChecked(state != Qt::Unchecked && state != Qt::PartiallyChecked);
    m_blockRefresh = false;
    update();
    publish();
}

void QCheckBox::publish() {
    const Qt::CheckState state = checkState();
    if (state == m_published)
        return;
    m_published = state;
    emit checkStateChanged(state);
    emit stateChanged(static_cast<int>(state));
}

/*!
    \reimp
*/
void QCheckBox::checkStateSet() {
    if (m_blockRefresh)
        return;
    m_partial = false;
    update();
    publish();
}

/*!
    \reimp

    A tristate check box goes from unchecked to partially checked to checked and back to unchecked.
*/
void QCheckBox::nextCheckState() {
    if (m_tristate)
        setCheckState(static_cast<Qt::CheckState>((static_cast<int>(checkState()) + 1) % 3));
    else
        QAbstractButton::nextCheckState();
}

