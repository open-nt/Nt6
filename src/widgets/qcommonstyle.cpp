#include <QtWidgets/qcommonstyle.h>

#include "qfusionstyle_p.h"

/*!
    \class QCommonStyle
    \brief The QCommonStyle class encapsulates the common Look and Feel of a GUI.

    QCommonStyle is the base for a style written from scratch: it draws every element, finds every part and
    answers every metric and hint, and a subclass reimplements what it draws in its own way. The elements and
    metrics that the subclass leaves alone are drawn with what it changes, as each element is drawn through
    QStyle::proxy().

    \code
    class Square : public QCommonStyle {
    public:
        void drawPrimitive(PrimitiveElement element, const QStyleOption *option, QPainter *painter,
                           const QWidget *widget) const override {
            if (element == PE_PanelButtonCommand) {
                painter->fillRect(option->rect, option->palette.button());
                return;
            }
            QCommonStyle::drawPrimitive(element, option, painter, widget);
        }
    };
    \endcode

    To change a few things about the application's style, derive from QProxyStyle instead.

    \differences
    The common look is that of Nt's default style, which is like Qt's Fusion style, where Qt's QCommonStyle draws
    a plainer look of its own. Nt's QFusionStyle does not derive from QCommonStyle.
    \enddifferences

    \sa QStyle, QProxyStyle
*/

/*!
    Constructs a common style.
*/
QCommonStyle::QCommonStyle() : m_look(std::make_unique<QFusionStyle>()) { m_look->m_proxy = this; }

/*!
    Destroys the style.
*/
QCommonStyle::~QCommonStyle() = default;

/*!
    \reimp
*/
void QCommonStyle::drawPrimitive(PrimitiveElement element, const QStyleOption *option, QPainter *painter,
                                 const QWidget *widget) const {
    m_look->drawPrimitive(element, option, painter, widget);
}

/*!
    \reimp
*/
void QCommonStyle::drawControl(ControlElement element, const QStyleOption *option, QPainter *painter,
                               const QWidget *widget) const {
    m_look->drawControl(element, option, painter, widget);
}

/*!
    \reimp
*/
QRect QCommonStyle::subElementRect(SubElement element, const QStyleOption *option, const QWidget *widget) const {
    return m_look->subElementRect(element, option, widget);
}

/*!
    \reimp
*/
int QCommonStyle::pixelMetric(PixelMetric metric, const QStyleOption *option, const QWidget *widget) const {
    return m_look->pixelMetric(metric, option, widget);
}

/*!
    \reimp
*/
QSize QCommonStyle::sizeFromContents(ContentsType type, const QStyleOption *option, const QSize &contentsSize,
                                     const QWidget *widget) const {
    return m_look->sizeFromContents(type, option, contentsSize, widget);
}

/*!
    \reimp
*/
QPalette QCommonStyle::standardPalette() const { return m_look->standardPalette(); }

