#include <QtCore/qchronotimer.h>

#include <QtCore/qcoreevent.h>

#include <algorithm>
#include <limits>

/*!
    Constructs a timer with the given \a parent and an interval of 0. The
    timer is not started.
*/
QChronoTimer::QChronoTimer(QObject *parent) : QObject(parent) {}

/*!
    Constructs a timer with the interval \a nsec and the given \a parent.
    The timer is not started.
*/
QChronoTimer::QChronoTimer(std::chrono::nanoseconds nsec, QObject *parent) : QObject(parent), m_interval(nsec) {}

/*!
    Destroys the timer, stopping it if it is running.
*/
QChronoTimer::~QChronoTimer() { stop(); }

int QChronoTimer::intervalMs() const {
    const auto ns = std::max<std::chrono::nanoseconds::rep>(m_interval.count(), 0);
    const auto ms = (ns + 999999) / 1000000;
    return static_cast<int>(std::min<std::chrono::nanoseconds::rep>(ms, std::numeric_limits<int>::max()));
}

/*!
    Sets the interval of the timer to \a nsec. If the timer is running, it is
    restarted with the new interval.

    \sa interval()
*/
void QChronoTimer::setInterval(std::chrono::nanoseconds nsec) {
    m_interval = nsec;
    if (m_id)
        start();
}

/*!
    Returns the interval of the timer.

    \sa setInterval()
*/
std::chrono::nanoseconds QChronoTimer::interval() const { return m_interval; }

/*!
    Returns the time left until the timer times out, zero if it is overdue,
    or -1 nanosecond if it is not running.
*/
std::chrono::nanoseconds QChronoTimer::remainingTime() const {
    if (!m_id)
        return std::chrono::nanoseconds(-1);
    const auto elapsed = std::chrono::steady_clock::now() - m_started;
    const auto left =
        std::chrono::duration_cast<std::chrono::nanoseconds>(std::chrono::milliseconds(intervalMs()) - elapsed);
    return std::max(left, std::chrono::nanoseconds(0));
}

/*!
    Sets whether the timer times out only once to \a singleShot.

    \sa isSingleShot()
*/
void QChronoTimer::setSingleShot(bool singleShot) { m_singleShot = singleShot; }

/*!
    Returns \c true if the timer times out only once; otherwise returns
    \c false.
*/
bool QChronoTimer::isSingleShot() const { return m_singleShot; }

/*!
    Sets the timer type to \a atype. It is recorded but does not change the
    precision in Nt.
*/
void QChronoTimer::setTimerType(Qt::TimerType atype) { m_type = atype; }

/*!
    Returns the timer type.
*/
Qt::TimerType QChronoTimer::timerType() const { return m_type; }

/*!
    Returns \c true if the timer is running; otherwise returns \c false.
*/
bool QChronoTimer::isActive() const { return m_id != 0; }

/*!
    Returns the ID of the running timer, or 0 if it is not running.
*/
int QChronoTimer::id() const { return m_id; }

/*!
    Starts or restarts the timer with its interval.

    \sa stop(), timeout()
*/
void QChronoTimer::start() {
    stop();
    m_started = std::chrono::steady_clock::now();
    m_id = startTimer(intervalMs());
}

/*!
    Stops the timer.

    \sa start()
*/
void QChronoTimer::stop() {
    if (m_id) {
        killTimer(m_id);
        m_id = 0;
    }
}

/*!
    \reimp
*/
void QChronoTimer::timerEvent(QTimerEvent *event) {
    if (event->timerId() != m_id) {
        QObject::timerEvent(event);
        return;
    }
    if (m_singleShot)
        stop();
    else
        m_started = std::chrono::steady_clock::now();
    timeout();
}

