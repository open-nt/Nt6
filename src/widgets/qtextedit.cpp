#include <QtWidgets/qtextedit.h>

/*!
    \class QTextEdit
    \brief The QTextEdit class is an editor for text of many lines, with the interface of Qt's rich text editor.

    A QTextEdit is a QPlainTextEdit with the functions that programs use to set and append text: setText() and append().
    It edits text without formatting. Use it when code written for Qt's QTextEdit has to compile, and QPlainTextEdit for new
    code:

    \code
    QTextEdit *log = new QTextEdit(window);
    log->setReadOnly(true);
    log->append("Started.");
    \endcode

    \differences
    There is no rich text: \c setHtml(), \c toHtml(), \c setMarkdown(), \c insertHtml(), \c setCurrentFont(), \c setTextColor()
    and the other functions that set the format of text are not there, and \c acceptRichText() does nothing. The text
    is plain: set and read it with setPlainText() and toPlainText(). A QTextEdit is a QPlainTextEdit here; in Qt the two
    classes are not related.
    \enddifferences

    \sa QPlainTextEdit
*/

/*!
    Constructs an empty editor with the given \a parent.
*/
QTextEdit::QTextEdit(QWidget *parent) : QPlainTextEdit(parent) {}

/*!
    Constructs an editor with the given \a text and \a parent.
*/
QTextEdit::QTextEdit(const QString &text, QWidget *parent) : QPlainTextEdit(text, parent) {}

/*!
    Destroys the editor.
*/
QTextEdit::~QTextEdit() = default;

/*!
    \fn bool QTextEdit::acceptRichText() const

    Returns whether the editor takes rich text from the clipboard. It has no effect: the text is always plain.

    \sa setAcceptRichText()
*/

/*!
    \fn void QTextEdit::setAcceptRichText(bool accept)

    Sets \a accept, which has no effect.

    \sa acceptRichText()
*/

/*!
    Sets the text to \a text, as setPlainText() does.
*/
void QTextEdit::setText(const QString &text) { setPlainText(text); }

/*!
    Appends a new line with \a text, as appendPlainText() does.
*/
void QTextEdit::append(const QString &text) { appendPlainText(text); }

