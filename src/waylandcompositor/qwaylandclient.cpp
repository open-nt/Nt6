#include <QtWaylandCompositor/qwaylandclient.h>

#include "qwaylandcompositor_p.h"

#include <csignal>

/*!
    \class QWaylandClient
    \brief The QWaylandClient class represents a client connected to the compositor.

    The compositor makes one for each connection and lists them in QWaylandCompositor::clients(). The
    process id, user id and group id come from the socket's credentials. close() disconnects the client,
    and kill() sends it a signal.

    \differences
    client() returns an opaque handle to the connection, not a libwayland \c wl_client; fromWlClient() takes that
    handle back. There is no text-input protocol, so textInputProtocols() is always NoProtocol.
    \enddifferences
*/

/*!
    \enum QWaylandClient::TextInputProtocol

    The text-input protocols a client can use. Nt implements none.

    \value NoProtocol No text-input protocol.
    \value QtTextInputMethodV1 The Qt text input method protocol.
    \value TextInputV2 The text-input-unstable-v2 protocol.
    \value TextInputV4 The text-input-unstable-v4 protocol.
*/

QWaylandClient::QWaylandClient(QWaylandCompositor *compositor, QtWaylandPrivate::Connection *connection)
    : QObject(compositor), m_compositor(compositor), m_connection(connection) {
    connection->userData = this;
}

/*!
    Destroys the client object. The connection, if still open, is closed.
*/
QWaylandClient::~QWaylandClient() {
    if (m_connection) {
        m_connection->userData = nullptr;
        if (!m_connection->isClosed())
            m_connection->close();
    }
}

/*!
    Returns the client of \a compositor whose handle is \a wlClient, or \c nullptr.
*/
QWaylandClient *QWaylandClient::fromWlClient(QWaylandCompositor *compositor, wl_client *wlClient) {
    if (!compositor)
        return nullptr;
    for (QWaylandClient *c : compositor->clients()) {
        if (c->client() == wlClient)
            return c;
    }
    return nullptr;
}

/*!
    Returns the handle of the connection, for fromWlClient().
*/
wl_client *QWaylandClient::client() const { return reinterpret_cast<wl_client *>(m_connection); }

/*!
    Returns the process id of the client.
*/
qint64 QWaylandClient::processId() const { return m_connection ? m_connection->processId() : 0; }

/*!
    Returns the user id of the client.
*/
qint64 QWaylandClient::userId() const { return m_connection ? m_connection->userId() : 0; }

/*!
    Returns the group id of the client.
*/
qint64 QWaylandClient::groupId() const { return m_connection ? m_connection->groupId() : 0; }

/*!
    Sends \a signal (SIGTERM by default) to the client's process.
*/
void QWaylandClient::kill(int signal) {
    if (processId() > 0)
        ::kill(static_cast<pid_t>(processId()), signal);
}

/*!
    Disconnects the client. Its surfaces are destroyed and the client object is deleted afterwards.
*/
void QWaylandClient::close() {
    if (m_connection && !m_connection->isClosed())
        m_connection->close();
}

