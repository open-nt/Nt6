"""Generates src/qregexunicodedata.cpp, the Unicode tables behind QRegularExpression.

Usage: gen_regex_unicode.py Scripts.txt PropertyValueAliases.txt > src/qregexunicodedata.cpp

General categories and simple case mappings come from Python's unicodedata module; scripts come
from the Unicode Character Database files Scripts.txt and PropertyValueAliases.txt. The data is
reproduced under the Unicode License (https://www.unicode.org/terms_of_use.html).
"""
import sys
import unicodedata

CATEGORIES = ["Cc", "Cf", "Cn", "Co", "Cs", "Ll", "Lm", "Lo", "Lt", "Lu", "Mc", "Me", "Mn", "Nd", "Nl", "No",
              "Pc", "Pd", "Pe", "Pf", "Pi", "Po", "Ps", "Sc", "Sk", "Sm", "So", "Zl", "Zp", "Zs"]
MAX = 0x110000


def category_runs():
    runs = []
    last = None
    for cp in range(MAX):
        cat = CATEGORIES.index(unicodedata.category(chr(cp)))
        if cat != last:
            runs.append((cp, cat))
            last = cat
    return runs


def single(s):
    return ord(s) if len(s) == 1 else None


def case_ranges(fn):
    # Merges code points with the same delta into ranges; stride 2 covers the alternating
    # upper/lower pairs of many scripts.
    pairs = []
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        m = single(fn(chr(cp)))
        if m is not None and m != cp:
            pairs.append((cp, m - cp))
    ranges = []
    i = 0
    while i < len(pairs):
        lo, delta = pairs[i]
        hi = lo
        stride = 1
        j = i + 1
        if j < len(pairs) and pairs[j][1] == delta and pairs[j][0] == lo + 1:
            stride = 1
        elif j < len(pairs) and pairs[j][1] == delta and pairs[j][0] == lo + 2:
            stride = 2
        while j < len(pairs) and pairs[j][1] == delta and pairs[j][0] == hi + stride:
            hi = pairs[j][0]
            j += 1
        ranges.append((lo, hi, delta, stride))
        i = j
    return ranges


def read_scripts(scripts_path, aliases_path):
    names = {}
    with open(aliases_path, encoding="utf-8") as f:
        for line in f:
            if not line.startswith("sc "):
                continue
            fields = [x.strip() for x in line.split("#")[0].split(";")]
            names[fields[2]] = [fields[1]] + fields[3:]
    ids = {}
    ordered = sorted(names)
    for i, n in enumerate(ordered):
        ids[n] = i
    runs_by_cp = {}
    with open(scripts_path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#")[0].strip()
            if not line:
                continue
            rng, name = [x.strip() for x in line.split(";")]
            lo, _, hi = rng.partition("..")
            lo = int(lo, 16)
            hi = int(hi, 16) if hi else lo
            runs_by_cp[lo] = (hi, ids[name])
    runs = []
    cp = 0
    unknown = ids["Unknown"]
    last = None
    starts = sorted(runs_by_cp)
    idx = 0
    while cp < MAX:
        if idx < len(starts) and starts[idx] == cp:
            hi, sid = runs_by_cp[cp]
            idx += 1
            nxt = hi + 1
        else:
            sid = unknown
            nxt = starts[idx] if idx < len(starts) else MAX
        if sid != last:
            runs.append((cp, sid))
            last = sid
        cp = nxt
    return ordered, names, runs


def main():
    scripts, aliases, script_runs = read_scripts(sys.argv[1], sys.argv[2])
    out = []
    w = out.append
    w("// MIT License - see LICENSE")
    w("// Generated by tools/gen_regex_unicode.py from Unicode %s data; do not edit." % unicodedata.unidata_version)
    w("// Unicode data is reproduced under the Unicode License: https://www.unicode.org/terms_of_use.html")
    w('#include "qregexunicode_p.h"')
    w("")
    w("namespace ntregex {")
    w("// clang-format off")
    w("const char *const kCategoryNames[kCategoryCount] = {")
    w("    " + ", ".join('"%s"' % c for c in CATEGORIES) + "};")
    runs = category_runs()
    w("const CategoryRun kCategoryRuns[] = {")
    for i in range(0, len(runs), 6):
        w("    " + " ".join("{0x%X, %d}," % r for r in runs[i:i + 6]))
    w("};")
    w("const int kCategoryRunCount = %d;" % len(runs))
    for name, fn in (("Lower", str.lower), ("Upper", str.upper)):
        rs = case_ranges(fn)
        w("const CaseRange k%sRanges[] = {" % name)
        for i in range(0, len(rs), 4):
            w("    " + " ".join("{0x%X, 0x%X, %d, %d}," % r for r in rs[i:i + 4]))
        w("};")
        w("const int k%sRangeCount = %d;" % (name, len(rs)))
    w("const ScriptName kScriptNames[] = {")
    count = 0
    for i, n in enumerate(scripts):
        for key in [n] + aliases[n]:
            w('    {"%s", %d},' % (key.replace("_", "").lower(), i))
            count += 1
    w("};")
    w("const int kScriptNameCount = %d;" % count)
    w("const ScriptRun kScriptRuns[] = {")
    for i in range(0, len(script_runs), 6):
        w("    " + " ".join("{0x%X, %d}," % r for r in script_runs[i:i + 6]))
    w("};")
    w("const int kScriptRunCount = %d;" % len(script_runs))
    w("const int kUnknownScript = %d;" % scripts.index("Unknown"))
    w("// clang-format on")
    w("} // namespace ntregex")
    sys.stdout.write("\n".join(out) + "\n")


main()
