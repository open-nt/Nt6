#include <QtGui/qrasterwindow.h>

/*!
    \class QRasterWindow
    \brief The QRasterWindow class is a convenience class for using QPainter on a QWindow.

    A raster window paints with QPainter into a software backing store.
    Reimplement paintEvent() and paint on the window:

    \code
    class Clock : public QRasterWindow {
    protected:
        void paintEvent(QPaintEvent *) override
        {
            QPainter painter(this);
            painter.fillRect(rect(), Qt::white);
            painter.setBrush(Qt::darkBlue);
            painter.drawEllipse(20, 20, 100, 100);
        }
    };
    \endcode

    \differences
    The class adds nothing to QPaintDeviceWindow, and the \a parent
    argument must be \c nullptr because Nt has no child windows.
    \enddifferences

    \sa QPaintDeviceWindow, QPainter
*/

/*!
    Constructs a raster window. \a parent is accepted for compatibility and
    must be \c nullptr.
*/
QRasterWindow::QRasterWindow(QWindow *parent) { (void)parent; }

/*!
    Destroys the window.
*/
QRasterWindow::~QRasterWindow() = default;

