#include <QtWidgets/qrubberband.h>

#include "qwidget_p.h"

#include <QtGui/qpainter.h>

/*!
    \class QRubberBand
    \brief The QRubberBand class draws a rectangle or a line that shows a selection or a new position.

    A rubber band follows the mouse while the user selects an area or moves something. Give it a geometry and show it:

    \code
    void Canvas::mousePressEvent(QMouseEvent *event) {
        m_origin = event->pos();
        m_band->setGeometry(QRect(m_origin, QSize()));
        m_band->show();
    }
    void Canvas::mouseMoveEvent(QMouseEvent *event) {
        m_band->setGeometry(QRect(m_origin, event->pos()).normalized());
    }
    \endcode

    A rubber band lets the mouse through to the widgets under it.

    \differences
    A rubber band is a child widget: without a parent it is a window, which Nt cannot make translucent, so give it the
    widget it is drawn over as the parent.
    \enddifferences

    \sa QFocusFrame
*/

/*!
    \enum QRubberBand::Shape

    How the rubber band is drawn.

    \value Line A filled line, such as where a splitter or a column will move to.
    \value Rectangle The outline of a rectangle, lightly filled, such as an area being selected.
*/

/*!
    Constructs a hidden rubber band of shape \a s in the widget \a p.
*/
QRubberBand::QRubberBand(Shape s, QWidget *p) : QWidget(p), m_shape(s) {
    QtPrivate::WidgetAccess::data(this).mouseTransparent = true;
    hide();
}

/*!
    Destroys the rubber band.
*/
QRubberBand::~QRubberBand() = default;

/*!
    \fn QRubberBand::Shape QRubberBand::shape() const

    Returns the shape of the rubber band.
*/

/*!
    \reimp
*/
void QRubberBand::paintEvent(QPaintEvent *event) {
    (void)event;
    QPainter painter(this);
    const QColor highlight = palette().color(QPalette::Active, QPalette::Highlight);
    if (m_shape == Line) {
        painter.fillRect(rect(), highlight);
        return;
    }
    // A light fill, mixed with the window color, and a border in the highlight color.
    const QColor window = palette().color(QPalette::Active, QPalette::Window);
    const QColor fill((highlight.red() + 3 * window.red()) / 4, (highlight.green() + 3 * window.green()) / 4,
                      (highlight.blue() + 3 * window.blue()) / 4);
    painter.fillRect(rect(), fill);
    painter.setPen(highlight);
    painter.setBrush(Qt::NoBrush);
    painter.drawRect(rect().adjusted(0, 0, -1, -1));
}

