/*!
    \module NtMultimediaWidgets
    \title Nt Multimedia Widgets C++ Classes
    \brief A widget that shows video.
    \cmaketarget Nt::MultimediaWidgets

    Nt Multimedia Widgets has QVideoWidget, which shows the frames of a camera in a user interface
    made with Nt Widgets. See \l{Using Nt Multimedia}.

    Link with \c Nt::MultimediaWidgets and include \c{<QVideoWidget>}.
*/

/*!
    \class QVideoWidget
    \inmodule NtMultimediaWidgets
    \brief The QVideoWidget class is a widget that shows video frames.

    Give the widget to a QMediaCaptureSession as its video output, and it shows the camera:

    \snippet multimedia/viewfinder.cpp viewfinder

    Frames arrive at the widget's videoSink(), and are drawn scaled to the widget, keeping their
    proportions by default, on black.

    \differences
    Frames are converted with QVideoFrame::toImage() and drawn with QPainter, without the GPU.
    setFullScreen() resizes a window to cover its screen and back, as Nt windows have no full screen
    state; a widget inside a window does not leave it. There is no QGraphicsVideoItem, as Nt Widgets
    has no graphics view.
    \enddifferences

    \sa QVideoSink, QMediaCaptureSession, QCamera
*/

/*!
    Constructs a video widget with the given \a parent.
*/
QVideoWidget::QVideoWidget(QWidget *parent) : QWidget(parent), m_sink(new QVideoSink(this)) {
    connect(m_sink, &QVideoSink::videoFrameChanged, this, [this](const QVideoFrame &f) { frameChanged(f); });
}

/*!
    Destroys the video widget.
*/
QVideoWidget::~QVideoWidget() = default;

/*!
    Returns the sink that receives the frames the widget shows. The widget owns it.
*/
QVideoSink *QVideoWidget::videoSink() const { return m_sink; }

/*!
    \fn bool QVideoWidget::isFullScreen() const

    Returns \c true if the widget covers its screen; otherwise returns \c false.
*/

/*!
    \fn Qt::AspectRatioMode QVideoWidget::aspectRatioMode() const

    Returns how frames are scaled to the widget.
*/

/*!
    Returns the size of the frames, or the size QWidget suggests before the first frame.
*/
QSize QVideoWidget::sizeHint() const {
    const QSize size = m_frame.size();
    if (!size.isEmpty())
        return size;
    return QWidget::sizeHint();
}

/*!
    Makes a top-level widget cover its screen if \a fullScreen is \c true, or go back to its
    previous geometry.
*/
void QVideoWidget::setFullScreen(bool fullScreen) {
    if (fullScreen == m_fullScreen)
        return;
    m_fullScreen = fullScreen;
    if (isWindow()) {
        if (fullScreen) {
            m_normalGeometry = geometry();
            if (QScreen *screen = QGuiApplication::primaryScreen())
                setGeometry(screen->geometry());
        } else if (m_normalGeometry.isValid()) {
            setGeometry(m_normalGeometry);
        }
    }
    emit fullScreenChanged(fullScreen);
}

/*!
    Sets how frames are scaled to the widget to \a mode: Qt::KeepAspectRatio (the default) fits
    the whole frame with black bars, Qt::KeepAspectRatioByExpanding fills the widget and crops the
    frame, and Qt::IgnoreAspectRatio stretches it.
*/
void QVideoWidget::setAspectRatioMode(Qt::AspectRatioMode mode) {
    if (mode == m_mode)
        return;
    m_mode = mode;
    update();
    emit aspectRatioModeChanged(mode);
}

void QVideoWidget::frameChanged(const QVideoFrame &frame) {
    const bool resized = frame.size() != m_frame.size();
    m_frame = frame;
    m_image = QImage();
    if (resized)
        updateGeometry();
    update();
}

/*!
    \reimp
*/
void QVideoWidget::paintEvent(QPaintEvent *event) {
    (void)event;
    QPainter painter(this);
    const QRect area = rect();
    painter.fillRect(area, Qt::black);
    if (m_image.isNull() && m_frame.isValid())
        m_image = m_frame.toImage();
    if (m_image.isNull() || area.isEmpty())
        return;
    QSize size = m_image.size();
    QRect target = area;
    if (m_mode != Qt::IgnoreAspectRatio) {
        size.scale(area.size(), m_mode);
        target = QRect(
            QPoint(area.x() + (area.width() - size.width()) / 2, area.y() + (area.height() - size.height()) / 2), size);
    }
    painter.drawImage(target, m_image);
}

