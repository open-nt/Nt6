#include <QtMultimedia/qaudioinput.h>
#include <QtMultimedia/qmediadevices.h>

#include <algorithm>

/*!
    \class QAudioInput
    \inmodule NtMultimedia
    \brief The QAudioInput class sets the device and volume a QMediaCaptureSession records from.

    \snippet multimedia/recorder.cpp record

    \differences
    None.
    \enddifferences

    \sa QMediaCaptureSession, QMediaRecorder, QAudioDevice
*/

/*!
    Constructs an input on the default audio input device, with the given \a parent.
*/
QAudioInput::QAudioInput(QObject *parent) : QAudioInput(QMediaDevices::defaultAudioInput(), parent) {}

/*!
    Constructs an input on \a deviceInfo, with the given \a parent.
*/
QAudioInput::QAudioInput(const QAudioDevice &deviceInfo, QObject *parent) : QObject(parent), m_device(deviceInfo) {}

/*!
    Destroys the input.
*/
QAudioInput::~QAudioInput() = default;

/*!
    Returns the device the input records from.
*/
QAudioDevice QAudioInput::device() const { return m_device; }

/*!
    Sets the device to record from to \a device. A null device selects the default one.
*/
void QAudioInput::setDevice(const QAudioDevice &device) {
    const QAudioDevice resolved = device.isNull() ? QMediaDevices::defaultAudioInput() : device;
    if (resolved == m_device)
        return;
    m_device = resolved;
    emit deviceChanged();
}

/*!
    Returns the gain applied to what is recorded, from 0.0 to 1.0.
*/
float QAudioInput::volume() const { return m_volume; }

/*!
    Sets the gain applied to what is recorded to \a volume, from 0.0 to 1.0.
*/
void QAudioInput::setVolume(float volume) {
    volume = std::clamp(volume, 0.0f, 1.0f);
    if (volume == m_volume)
        return;
    m_volume = volume;
    emit volumeChanged(volume);
}

/*!
    Returns \c true if the input is muted; otherwise returns \c false.
*/
bool QAudioInput::isMuted() const { return m_muted; }

/*!
    Mutes the input if \a muted is \c true, or unmutes it. A muted input records silence.
*/
void QAudioInput::setMuted(bool muted) {
    if (muted == m_muted)
        return;
    m_muted = muted;
    emit mutedChanged(muted);
}

