/*!
    \class QGeoCircle
    \inmodule NtPositioning
    \brief The QGeoCircle class defines a circular geographic area.

    The circle is given by its centre and a radius in metres along the surface; contains() measures
    the great-circle distance to the centre.

    \code
    const QGeoCircle exclusion(QGeoCoordinate(51.1789, -1.8262), 2000.0);
    exclusion.contains(vehicle);
    \endcode

    \differences
    There is no QDataStream operator.
    \enddifferences

    \sa QGeoShape, QGeoRectangle
*/

/*!
    Constructs an invalid circle.
*/
QGeoCircle::QGeoCircle() : QGeoShape(CircleType) {}

/*!
    Constructs a circle centred on \a center with \a radius metres. The circle is invalid if the
    centre is invalid or the radius is negative.
*/
QGeoCircle::QGeoCircle(const QGeoCoordinate &center, qreal radius) : QGeoShape(CircleType) {
    m_a = center;
    m_radius = radius;
}

/*!
    Constructs a copy of \a other if it is a circle; otherwise constructs an invalid circle.
*/
QGeoCircle::QGeoCircle(const QGeoShape &other) : QGeoShape(other) {
    if (other.type() != CircleType)
        *this = QGeoCircle();
}

/*!
    \fn void QGeoCircle::setCenter(const QGeoCoordinate &center)
    Sets the centre to \a center.
*/

/*!
    \fn QGeoCoordinate QGeoCircle::center() const
    Returns the centre.
*/

/*!
    \fn void QGeoCircle::setRadius(qreal radius)
    Sets the radius to \a radius metres.
*/

/*!
    \fn qreal QGeoCircle::radius() const
    Returns the radius in metres; negative for an invalid circle.
*/

/*!
    Moves the centre \a degreesLatitude degrees north and \a degreesLongitude degrees east. The
    latitude is clamped at the poles.
*/
void QGeoCircle::translate(double degreesLatitude, double degreesLongitude) {
    if (!m_a.isValid())
        return;
    const double latitude = std::clamp(m_a.latitude() + degreesLatitude, -90.0, 90.0);
    m_a = QGeoCoordinate(latitude, QtPositioningPrivate::normalizeLongitude(m_a.longitude() + degreesLongitude),
                         m_a.altitude());
}

/*!
    Returns a copy of the circle moved \a degreesLatitude degrees north and \a degreesLongitude
    degrees east.

    \sa translate()
*/
QGeoCircle QGeoCircle::translated(double degreesLatitude, double degreesLongitude) const {
    QGeoCircle result(*this);
    result.translate(degreesLatitude, degreesLongitude);
    return result;
}

/*!
    Grows the radius, keeping the centre, so that the circle contains \a coordinate. Nothing
    changes if either is invalid.
*/
void QGeoCircle::extendCircle(const QGeoCoordinate &coordinate) {
    if (!isValid() || !coordinate.isValid() || contains(coordinate))
        return;
    m_radius = m_a.distanceTo(coordinate);
}

/*!
    Returns the circle as text: \c{QGeoCircle({latitude, longitude}, radius)}.
*/
QString QGeoCircle::toString() const {
    return QStringLiteral("QGeoCircle({%1, %2}, %3)").arg(m_a.latitude()).arg(m_a.longitude()).arg(m_radius);
}

