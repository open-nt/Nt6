#include <QtHttpServer/qhttpserverrequest.h>

/*!
    \class QHttpServerRequest
    \brief The QHttpServerRequest class holds a request that a QAbstractHttpServer received.
    \since 6.4

    The server reads the whole request, including its body, before it hands
    the request to a handler. A request holds the method, the URL, the header
    fields, the body and the addresses of both ends of the connection.

    The URL is absolute: its scheme is \c http, or \c https on an encrypted
    connection, and its host and port come from the \c Host header, or from
    the local address when the request has none.

    \code
    server.route("/echo", QHttpServerRequest::Method::Post, [](const QHttpServerRequest &request) {
        return QHttpServerResponse("text/plain", request.body());
    });
    \endcode

    \differences
    There is no \c sslConfiguration(). remoteAddress(), remotePort(),
    localAddress() and localPort() return a null address and 0 for requests
    that arrived on a QLocalServer.
    \enddifferences

    \sa QHttpServer, QHttpServerResponder
*/

/*!
    \enum QHttpServerRequest::Method

    The method of a request. The values can be combined into
    QHttpServerRequest::Methods to say which methods a route accepts.

    \value Unknown A method that is not one of the others, such as \c PROPFIND.
    \value Get \c GET
    \value Put \c PUT
    \value Delete \c DELETE
    \value Post \c POST
    \value Head \c HEAD. The server leaves the body out of the response.
    \value Options \c OPTIONS
    \value Patch \c PATCH
    \value Connect \c CONNECT
    \value Trace \c TRACE
    \value AnyKnown All of the above except \c Unknown.
*/

/*!
    \typedef QHttpServerRequest::Methods

    A QFlags of Method values.
*/

/*!
    Constructs a copy of \a other.
*/
QHttpServerRequest::QHttpServerRequest(const QHttpServerRequest &other) = default;

/*!
    Move-constructs a request from \a other.
*/
QHttpServerRequest::QHttpServerRequest(QHttpServerRequest &&other) noexcept = default;

/*!
    Assigns \a other to this request and returns a reference to it.
*/
QHttpServerRequest &QHttpServerRequest::operator=(const QHttpServerRequest &other) = default;

/*!
    \overload

    Move-assigns \a other to this request and returns a reference to it.
*/
QHttpServerRequest &QHttpServerRequest::operator=(QHttpServerRequest &&other) noexcept = default;

/*!
    Destroys the request.
*/
QHttpServerRequest::~QHttpServerRequest() = default;

/*!
    Returns the value of the first header field named \a key, compared
    without regard to case, or an empty QByteArray if there is none.

    \sa headers()
*/
QByteArray QHttpServerRequest::value(const QByteArray &key) const { return m_headers.value(key).toByteArray(); }

/*!
    Returns the absolute URL of the request.

    \sa query()
*/
QUrl QHttpServerRequest::url() const { return m_url; }

/*!
    Returns the query of the URL.

    \sa url()
*/
QUrlQuery QHttpServerRequest::query() const { return QUrlQuery(m_url); }

/*!
    Returns the method of the request.
*/
QHttpServerRequest::Method QHttpServerRequest::method() const { return m_method; }

/*!
    Returns the body of the request. A body sent with chunked transfer coding
    is returned decoded.
*/
QByteArray QHttpServerRequest::body() const { return m_body; }

/*!
    Returns the address of the client.

    \sa remotePort(), localAddress()
*/
QHostAddress QHttpServerRequest::remoteAddress() const { return m_remoteAddress; }

/*!
    Returns the port of the client.

    \sa remoteAddress()
*/
quint16 QHttpServerRequest::remotePort() const { return m_remotePort; }

/*!
    Returns the address of the server that received the request.

    \sa localPort(), remoteAddress()
*/
QHostAddress QHttpServerRequest::localAddress() const { return m_localAddress; }

/*!
    Returns the port of the server that received the request.

    \sa localAddress()
*/
quint16 QHttpServerRequest::localPort() const { return m_localPort; }

