#include <QtMultimediaWidgets/qgraphicsvideoitem.h>

#include <QtGui/qpainter.h>
#include <QtMultimedia/qvideosink.h>

/*!
    \class QGraphicsVideoItem
    \inmodule NtMultimediaWidgets
    \brief The QGraphicsVideoItem class shows video frames in a QGraphicsScene.

    Give the item to a QMediaCaptureSession or QMediaPlayer as its video output. Frames arrive at its
    videoSink() and are drawn into the rectangle given by offset() and size(), scaled as aspectRatioMode()
    says:

    \code
    auto *video = new QGraphicsVideoItem;
    video->setSize(QSizeF(640, 480));
    scene.addItem(video);
    session.setVideoOutput(video);
    \endcode

    \differences
    Frames are converted with QVideoFrame::toImage() and drawn with QPainter, without the GPU. Nt's
    QMediaPlayer plays no video, so the item shows frames from a capture session or from a sink fed directly.
    \enddifferences

    \sa QVideoWidget, QVideoSink
*/

/*!
    Constructs a video item, a child of \a parent.
*/
QGraphicsVideoItem::QGraphicsVideoItem(QGraphicsItem *parent) : QGraphicsObject(parent), m_sink(new QVideoSink(this)) {
    connect(m_sink, &QVideoSink::videoFrameChanged, this, [this](const QVideoFrame &f) { frameChanged(f); });
}

/*!
    Destroys the video item.
*/
QGraphicsVideoItem::~QGraphicsVideoItem() = default;

/*!
    Returns the sink that receives the frames the item shows. The item owns it.
*/
QVideoSink *QGraphicsVideoItem::videoSink() const { return m_sink; }

/*!
    Returns how frames are scaled to size(); Qt::KeepAspectRatio by default.
*/
Qt::AspectRatioMode QGraphicsVideoItem::aspectRatioMode() const { return m_mode; }

/*!
    Sets how frames are scaled to size() to \a mode.
*/
void QGraphicsVideoItem::setAspectRatioMode(Qt::AspectRatioMode mode) {
    if (mode == m_mode)
        return;
    m_mode = mode;
    update();
}

/*!
    Returns the top left of the video area in item coordinates.
*/
QPointF QGraphicsVideoItem::offset() const { return m_offset; }

/*!
    Moves the video area to \a offset in item coordinates.
*/
void QGraphicsVideoItem::setOffset(const QPointF &offset) {
    if (offset == m_offset)
        return;
    prepareGeometryChange();
    m_offset = offset;
}

/*!
    Returns the size of the video area; 320 by 240 by default.
*/
QSizeF QGraphicsVideoItem::size() const { return m_size; }

/*!
    Sets the size of the video area to \a size.
*/
void QGraphicsVideoItem::setSize(const QSizeF &size) {
    if (size == m_size)
        return;
    prepareGeometryChange();
    m_size = size;
}

/*!
    Returns the size of the frames, or an empty size before the first frame.
*/
QSizeF QGraphicsVideoItem::nativeSize() const { return m_nativeSize; }

void QGraphicsVideoItem::frameChanged(const QVideoFrame &frame) {
    m_frame = frame;
    m_image = QImage();
    const QSizeF native(frame.size());
    if (native != m_nativeSize) {
        m_nativeSize = native;
        emit nativeSizeChanged(native);
    }
    update();
}

// The rectangle the frame is drawn into, inside the video area.
QRectF QGraphicsVideoItem::videoRect() const {
    const QRectF area(m_offset, m_size);
    if (m_nativeSize.isEmpty() || m_mode == Qt::IgnoreAspectRatio)
        return area;
    const QSizeF scaled = m_nativeSize.scaled(m_size, m_mode);
    return QRectF(area.center() - QPointF(scaled.width() / 2, scaled.height() / 2), scaled);
}

/*!
    \reimp
*/
QRectF QGraphicsVideoItem::boundingRect() const { return QRectF(m_offset, m_size); }

/*!
    \reimp
*/
void QGraphicsVideoItem::paint(QPainter *painter, const QStyleOptionGraphicsItem *option, QWidget *widget) {
    Q_UNUSED(option);
    Q_UNUSED(widget);
    if (!m_frame.isValid())
        return;
    if (m_image.isNull())
        m_image = m_frame.toImage();
    if (m_image.isNull())
        return;
    const QRectF area(m_offset, m_size);
    painter->save();
    painter->setClipRect(area, Qt::IntersectClip);
    painter->drawImage(videoRect(), m_image);
    painter->restore();
}

/*!
    \reimp
*/
int QGraphicsVideoItem::type() const { return Type; }

