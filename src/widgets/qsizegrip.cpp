#include <QtWidgets/qsizegrip.h>

#include <QtGui/qevent.h>
#include <QtGui/qpainter.h>

#include <algorithm>

/*!
    \class QSizeGrip
    \brief The QSizeGrip class provides a corner handle for resizing a window.

    A size grip sits in the bottom right corner of a window, often in a status bar. Dragging it resizes the window
    that contains it, within the minimum and maximum size of the window:

    \code
    auto *grip = new QSizeGrip(window);
    layout->addWidget(grip, 0, Qt::AlignBottom | Qt::AlignRight);
    \endcode

    \differences
    The grip resizes the window itself rather than asking the window manager to, and it is always in the bottom
    right corner: it does not hide when the window is maximized or move for right-to-left layouts.
    \enddifferences

    \sa QStatusBar
*/

/*!
    Constructs a size grip in \a parent, which resizes the window of \a parent.
*/
QSizeGrip::QSizeGrip(QWidget *parent) : QWidget(parent) { setSizePolicy(QSizePolicy::Fixed, QSizePolicy::Fixed); }

/*!
    Destroys the size grip.
*/
QSizeGrip::~QSizeGrip() = default;

/*!
    \reimp
*/
QSize QSizeGrip::sizeHint() const { return QSize(13, 13); }

/*!
    \reimp
*/
void QSizeGrip::paintEvent(QPaintEvent *event) {
    (void)event;
    QPainter painter(this);
    const QPalette::ColorGroup group = isEnabled() ? QPalette::Active : QPalette::Disabled;
    // Three diagonal lines in the bottom right corner.
    painter.setPen(palette().color(group, QPalette::Mid));
    const int w = width(), h = height();
    for (int offset = 3; offset <= 11; offset += 4)
        painter.drawLine(w - 1, h - offset, w - offset, h - 1);
}

/*!
    \reimp
*/
void QSizeGrip::mousePressEvent(QMouseEvent *event) {
    if (event->button() != Qt::LeftButton) {
        event->ignore();
        return;
    }
    m_dragging = true;
    m_pressGlobal = event->globalPosition().toPoint();
    m_startSize = window()->size();
    event->accept();
}

/*!
    \reimp

    While the grip is dragged the window takes the size it started with plus the distance the mouse moved.
*/
void QSizeGrip::mouseMoveEvent(QMouseEvent *event) {
    if (!m_dragging) {
        event->ignore();
        return;
    }
    QWidget *top = window();
    const QPoint delta = event->globalPosition().toPoint() - m_pressGlobal;
    const QSize minimum = top->minimumSize().expandedTo(top->minimumSizeHint());
    const QSize maximum = top->maximumSize();
    const QSize size(
        std::clamp(m_startSize.width() + delta.x(), minimum.width(), std::max(minimum.width(), maximum.width())),
        std::clamp(m_startSize.height() + delta.y(), minimum.height(), std::max(minimum.height(), maximum.height())));
    top->resize(size);
    event->accept();
}

/*!
    \reimp
*/
void QSizeGrip::mouseReleaseEvent(QMouseEvent *event) {
    if (event->button() != Qt::LeftButton || !m_dragging) {
        event->ignore();
        return;
    }
    m_dragging = false;
    event->accept();
}

