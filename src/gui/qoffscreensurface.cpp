#include <QtGui/qoffscreensurface.h>

#include "qegl_p.h"
#include "qwindow_p.h"

#include <QtCore/qdebug.h>
#include <QtGui/qguiapplication.h>

/*!
    \class QOffscreenSurface
    \inmodule NtGui
    \since 6.0
    \brief The QOffscreenSurface class represents an offscreen surface in the underlying platform.

    An offscreen surface lets a QOpenGLContext be current without a window,
    to create textures or render into a framebuffer object:

    \code
    QOffscreenSurface surface;
    surface.create();
    QOpenGLContext context;
    context.create();
    context.makeCurrent(&surface);
    \endcode

    \differences
    The surface is a surfaceless EGL context where EGL allows that, and
    otherwise a pbuffer of one pixel. There is no native handle.
    \enddifferences

    \sa QOpenGLContext
*/

/*!
    Constructs an offscreen surface for \a screen, or for the primary screen if
    it is \c nullptr, with the given \a parent. Call create() before using it.
*/
QOffscreenSurface::QOffscreenSurface(QScreen *screen, QObject *parent)
    : QObject(parent), QSurface(QSurface::Offscreen), m_screen(screen ? screen : QGuiApplication::primaryScreen()) {}

/*!
    Destroys the surface.
*/
QOffscreenSurface::~QOffscreenSurface() { destroy(); }

/*!
    \fn QSurface::SurfaceType QOffscreenSurface::surfaceType() const

    Returns QSurface::OpenGLSurface.
*/

/*!
    Creates the surface. It is valid if OpenGL is available.

    \sa isValid(), destroy()
*/
void QOffscreenSurface::create() {
    const QtPrivate::Egl::Display &d = QtPrivate::Egl::display();
    if (!d.display)
        qWarning("QOffscreenSurface::create(): %s", qPrintable(d.error));
    m_valid = d.display != nullptr;
}

/*!
    Releases what OpenGL made for the surface.

    \sa create()
*/
void QOffscreenSurface::destroy() {
    if (!m_valid)
        return;
    QtPrivate::GuiAccess::surfaceAboutToBeDestroyed(this);
    m_valid = false;
}

/*!
    \fn bool QOffscreenSurface::isValid() const

    Returns \c true if create() made the surface.
*/

/*!
    \fn void QOffscreenSurface::setFormat(const QSurfaceFormat &format)

    Sets the requested \a format.
*/

/*!
    \fn QSurfaceFormat QOffscreenSurface::format() const

    Returns the format of the surface.
*/

/*!
    \fn QSurfaceFormat QOffscreenSurface::requestedFormat() const

    Returns the format set with setFormat(), or QSurfaceFormat::defaultFormat().
*/

/*!
    \fn QSize QOffscreenSurface::size() const

    Returns the size of the surface, which is one by one pixel.
*/

/*!
    \fn QScreen *QOffscreenSurface::screen() const

    Returns the screen of the surface.
*/

/*!
    Sets the screen of the surface to \a screen, or to the primary screen if it
    is \c nullptr.
*/
void QOffscreenSurface::setScreen(QScreen *screen) {
    QScreen *next = screen ? screen : QGuiApplication::primaryScreen();
    if (next == m_screen)
        return;
    m_screen = next;
    emit screenChanged(next);
}

