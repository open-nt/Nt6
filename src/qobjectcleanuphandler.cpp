#include <QtCore/qobjectcleanuphandler.h>

/*!
    \class QObjectCleanupHandler
    \brief The QObjectCleanupHandler class watches the lifetime of multiple QObjects.

    A cleanup handler deletes the objects that were added to it when it is
    destroyed or cleared, and forgets objects that are deleted by someone else
    first, so it never deletes an object twice. It is useful to tie the
    lifetime of several unrelated objects to one owner:

    \code
    QObjectCleanupHandler cleaners;
    QTimer *timer = cleaners.add(new QTimer);
    QFile *file = cleaners.add(new QFile("log.txt"));
    // both are deleted when `cleaners` goes out of scope
    \endcode

    Objects are deleted in the reverse order in which they were added.

    \differences
    None.
    \enddifferences

    \sa QPointer, QObject::destroyed()
*/

/*!
    Constructs an empty cleanup handler.
*/
QObjectCleanupHandler::QObjectCleanupHandler() = default;

/*!
    Destroys the cleanup handler, deleting all objects that were added to it.

    \sa clear()
*/
QObjectCleanupHandler::~QObjectCleanupHandler() { clear(); }

/*!
    Adds \a object to the handler and returns it. The handler deletes the
    object when it is cleared or destroyed, unless the object is deleted before
    that. Adding a null pointer does nothing and returns \c nullptr.

    \sa remove()
*/
QObject *QObjectCleanupHandler::add(QObject *object) {
    if (!object)
        return nullptr;
    m_objects.append(object);
    QObject::connect(object, &QObject::destroyed, this, [this](QObject *gone) { m_objects.removeAll(gone); });
    return object;
}

/*!
    Removes \a object from the handler, which then no longer deletes it.

    \sa add()
*/
void QObjectCleanupHandler::remove(QObject *object) {
    if (m_objects.removeAll(object) > 0)
        QObject::disconnect(object, &QObject::destroyed, this);
}

/*!
    Returns \c true if the handler holds no objects.

    \sa clear()
*/
bool QObjectCleanupHandler::isEmpty() const { return m_objects.isEmpty(); }

/*!
    Deletes all objects in the handler, in the reverse order in which they were
    added, and leaves it empty.

    \sa isEmpty()
*/
void QObjectCleanupHandler::clear() {
    while (!m_objects.isEmpty()) {
        QObject *object = m_objects.takeLast();
        QObject::disconnect(object, &QObject::destroyed, this);
        delete object;
    }
}

