#include <QtMultimedia/qaudiooutput.h>
#include <QtMultimedia/qmediadevices.h>

#include <algorithm>

/*!
    \class QAudioOutput
    \inmodule NtMultimedia
    \brief The QAudioOutput class sets the device and volume a QMediaPlayer plays on.

    \snippet multimedia/audioplayer.cpp player

    \differences
    None.
    \enddifferences

    \sa QMediaPlayer, QAudioDevice
*/

/*!
    Constructs an output on the default audio device, with the given \a parent.
*/
QAudioOutput::QAudioOutput(QObject *parent) : QAudioOutput(QMediaDevices::defaultAudioOutput(), parent) {}

/*!
    Constructs an output on \a device, with the given \a parent.
*/
QAudioOutput::QAudioOutput(const QAudioDevice &device, QObject *parent) : QObject(parent), m_device(device) {}

/*!
    Destroys the output.
*/
QAudioOutput::~QAudioOutput() = default;

/*!
    Returns the device the output plays on.
*/
QAudioDevice QAudioOutput::device() const { return m_device; }

/*!
    Sets the device to play on to \a device. A null device selects the default one.
*/
void QAudioOutput::setDevice(const QAudioDevice &device) {
    const QAudioDevice resolved = device.isNull() ? QMediaDevices::defaultAudioOutput() : device;
    if (resolved == m_device)
        return;
    m_device = resolved;
    emit deviceChanged();
}

/*!
    Returns the volume, from 0.0 to 1.0.
*/
float QAudioOutput::volume() const { return m_volume; }

/*!
    Sets the volume to \a volume, from 0.0 to 1.0.

    \sa QtAudio::convertVolume()
*/
void QAudioOutput::setVolume(float volume) {
    volume = std::clamp(volume, 0.0f, 1.0f);
    if (volume == m_volume)
        return;
    m_volume = volume;
    emit volumeChanged(volume);
}

/*!
    Returns \c true if the output is muted; otherwise returns \c false.
*/
bool QAudioOutput::isMuted() const { return m_muted; }

/*!
    Mutes the output if \a muted is \c true, or unmutes it.
*/
void QAudioOutput::setMuted(bool muted) {
    if (muted == m_muted)
        return;
    m_muted = muted;
    emit mutedChanged(muted);
}

