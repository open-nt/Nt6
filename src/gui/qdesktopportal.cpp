#include "qpa/qdesktopportal_p.h"

#include <QtDBus/qdbusconnection.h>
#include <QtDBus/qdbusextratypes.h>
#include <QtDBus/qdbusmessage.h>

namespace {

const char *const kService = "org.freedesktop.portal.Desktop";
const char *const kPath = "/org/freedesktop/portal/desktop";
const char *const kInterface = "org.freedesktop.portal.Settings";
const char *const kAppearance = "org.freedesktop.appearance";
const char *const kColorScheme = "color-scheme";

// The portal wraps the value of Read() in a variant of its own; peel off every layer.
QVariant unwrap(QVariant value) {
    while (value.canConvert<QDBusVariant>())
        value = value.value<QDBusVariant>().variant();
    return value;
}

} // namespace

QDesktopPortalSettings::QDesktopPortalSettings(QObject *parent) : QObject(parent) {
    QDBusConnection bus = QDBusConnection::sessionBus();
    if (!bus.isConnected())
        return;
    QDBusMessage call = QDBusMessage::createMethodCall(QString::fromLatin1(kService), QString::fromLatin1(kPath),
                                                       QString::fromLatin1(kInterface), QString::fromLatin1("Read"));
    call << QString::fromLatin1(kAppearance) << QString::fromLatin1(kColorScheme);
    const QDBusMessage reply = bus.call(call, QDBus::Block, 500);
    if (reply.type() == QDBusMessage::ReplyMessage && !reply.arguments().isEmpty()) {
        const QVariant value = unwrap(reply.arguments().at(0));
        if (value.canConvert<unsigned>())
            m_scheme = schemeFromValue(value.toUInt());
    }
    bus.connect(QString::fromLatin1(kService), QString::fromLatin1(kPath), QString::fromLatin1(kInterface),
                QString::fromLatin1("SettingChanged"), this, SLOT(settingChanged(QString, QString, QDBusVariant)));
}

Qt::ColorScheme QDesktopPortalSettings::schemeFromValue(unsigned value) {
    switch (value) {
    case 1:
        return Qt::ColorScheme::Dark;
    case 2:
        return Qt::ColorScheme::Light;
    default:
        return Qt::ColorScheme::Unknown; // "no preference"
    }
}

void QDesktopPortalSettings::settingChanged(const QString &nameSpace, const QString &key, const QDBusVariant &value) {
    if (nameSpace != QString::fromLatin1(kAppearance) || key != QString::fromLatin1(kColorScheme))
        return;
    const QVariant inner = unwrap(value.variant());
    if (!inner.canConvert<unsigned>())
        return;
    const Qt::ColorScheme scheme = schemeFromValue(inner.toUInt());
    if (scheme == m_scheme)
        return;
    m_scheme = scheme;
    colorSchemeChanged(scheme);
}

