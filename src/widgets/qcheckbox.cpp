#include <QtWidgets/qcheckbox.h>

#include <QtGui/qpainter.h>
#include <QtWidgets/qstyle.h>
#include <QtWidgets/qstyleoption.h>

/*!
    \class QCheckBox
    \brief The QCheckBox class provides a checkbox with a text label.

    A check box is a checkable button that shows its state in an indicator next to the text. Connect to
    toggled():

    \code
    QCheckBox *box = new QCheckBox("Remember me", window);
    box->setChecked(true);
    \endcode

    \differences
    There are no tristate check boxes and no \c stateChanged() signal or \c checkState(); use toggled() and isChecked().
    \enddifferences

    \sa QAbstractButton, QPushButton
*/

/*!
    Constructs a check box with no text and the given \a parent.
*/
QCheckBox::QCheckBox(QWidget *parent) : QAbstractButton(parent) {
    setCheckable(true);
    setSizePolicy(QSizePolicy::Minimum, QSizePolicy::Fixed);
}

/*!
    Constructs a check box that shows \a text, with the given \a parent.
*/
QCheckBox::QCheckBox(const QString &text, QWidget *parent) : QAbstractButton(parent) {
    setCheckable(true);
    setSizePolicy(QSizePolicy::Minimum, QSizePolicy::Fixed);
    setText(text);
}

/*!
    Destroys the check box.
*/
QCheckBox::~QCheckBox() = default;

/*!
    \reimp
*/
QSize QCheckBox::sizeHint() const {
    const QSize text = fontMetrics().size(Qt::TextSingleLine, this->text());
    QStyleOptionButton option;
    option.initFrom(this);
    option.text = this->text();
    return style()->sizeFromContents(QStyle::CT_CheckBox, &option, text, this);
}

/*!
    \reimp
*/
bool QCheckBox::hitButton(const QPoint &pos) const {
    const QSize hint = sizeHint();
    return QRect(0, 0, std::min(width(), hint.width()), height()).contains(pos);
}

/*!
    \reimp
*/
void QCheckBox::paintEvent(QPaintEvent *event) {
    (void)event;
    QPainter painter(this);
    painter.setFont(font());
    QStyleOptionButton option;
    option.initFrom(this);
    option.text = text();
    option.state |= isDown() ? QStyle::State_Sunken : QStyle::State_Raised;
    option.state |= isChecked() ? QStyle::State_On : QStyle::State_Off;
    style()->drawControl(QStyle::CE_CheckBox, &option, &painter, this);
}

