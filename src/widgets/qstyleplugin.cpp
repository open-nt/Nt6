#include <QtWidgets/qstyleplugin.h>

/*!
    \class QStylePlugin
    \brief The QStylePlugin class is the base class for objects that make styles by name.

    Subclass it and implement create() to return a style for the keys that it knows:

    \code
    class RetroPlugin : public QStylePlugin {
    public:
        QStyle *create(const QString &key) override {
            return key.compare("retro", Qt::CaseInsensitive) == 0 ? new RetroStyle : nullptr;
        }
    };
    \endcode

    \differences
    Nt has no plug-in loader, so QStyleFactory does not ask a QStylePlugin: an application calls create() itself.
    \enddifferences

    \sa QStyleFactory, QStyle
*/

/*!
    Constructs a style plug-in with the given \a parent.
*/
QStylePlugin::QStylePlugin(QObject *parent) : QObject(parent) {}

/*!
    Destroys the plug-in.
*/
QStylePlugin::~QStylePlugin() = default;

