#include <QtDBus/qdbusabstractadaptor.h>

#include <vector>

/*!
    \class QDBusAbstractAdaptor
    \brief The QDBusAbstractAdaptor class is the base class of D-Bus adaptor classes.

    An adaptor exports one D-Bus interface of the object that is its parent. Its public slots
    become methods, its signals D-Bus signals and its properties D-Bus properties; the class
    information \c{"D-Bus Interface"} names the interface:

    \snippet dbus/clock.cpp adaptor

    Create the adaptor with the object as its parent, then register the object with
    QDBusConnection::registerObject(). The adaptor is destroyed with the object.

    \differences
    The adaptor must exist when the object is registered for its signals to be relayed. The
    class information \c{"D-Bus Introspection"}, if present, is used as the introspection data
    of the interface as it is.
    \enddifferences

    \sa QDBusConnection::registerObject(), QDBusContext
*/

/*!
    Constructs an adaptor for \a parent, which becomes its parent.
*/
QDBusAbstractAdaptor::QDBusAbstractAdaptor(QObject *parent) : QObject(parent) {}

/*!
    Destroys the adaptor.
*/
QDBusAbstractAdaptor::~QDBusAbstractAdaptor() {
    for (const auto &c : m_relays)
        QObject::disconnect(c);
}

/*!
    Sets whether each signal of the adaptor is emitted when the parent emits a signal of the
    same name and parameters to \a enable. Call it in the constructor of the subclass.
*/
void QDBusAbstractAdaptor::setAutoRelaySignals(bool enable) {
    for (const auto &c : m_relays)
        QObject::disconnect(c);
    m_relays.clear();
    m_autoRelay = enable;
    QObject *source = parent();
    if (!enable || !source)
        return;
    const QMetaObject *mine = metaObject();
    const QMetaObject *theirs = source->metaObject();
    for (int i = QDBusAbstractAdaptor::staticMetaObject.methodCount(); i < mine->methodCount(); ++i) {
        const QMetaMethod m = mine->method(i);
        if (m.methodType() != QMetaMethod::Signal || (m.attributes() & QMetaMethod::Cloned))
            continue;
        const int index = theirs->indexOfSignal(m.methodSignature().constData());
        if (index < 0)
            continue;
        const int count = m.parameterCount();
        m_relays.append(QtPrivate::Access::connectFunction(
            source, theirs->method(index), this, [this, i, count](void *const *argv) {
                std::vector<void *> a(static_cast<std::size_t>(count) + 1, nullptr);
                for (int k = 0; k < count; ++k)
                    a[static_cast<std::size_t>(k) + 1] = argv[k];
                QMetaObject::activate(this, i, a.data());
            }));
    }
}

/*!
    Returns \c true if the adaptor relays the signals of its parent.
*/
bool QDBusAbstractAdaptor::autoRelaySignals() const { return m_autoRelay; }

