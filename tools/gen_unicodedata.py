"""Generates src/qunicodedata_p.h from Python's Unicode Character Database.

Usage: tools/gen_unicodedata.py src/qunicodedata_p.h
"""
import sys
import unicodedata

CATEGORIES = ["Mn", "Mc", "Me", "Nd", "Nl", "No", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co", "Cn",
              "Lu", "Ll", "Lt", "Lm", "Lo", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So"]


def wrap(items, indent="   ", width=110):
    lines, line = [], indent
    for item in items:
        if len(line) + len(item) + 1 > width:
            lines.append(line)
            line = indent
        line += " " + item
    lines.append(line)
    return lines


def category_runs():
    index = {c: i for i, c in enumerate(CATEGORIES)}
    runs, previous = [], None
    for cp in range(0x110000):
        c = unicodedata.category(chr(cp))
        if c != previous:
            runs.append((cp << 5) | index[c])
            previous = c
    return runs


def decompositions():
    result = []
    for cp in range(0xC0, 0x2000):
        d = unicodedata.normalize("NFD", chr(cp))
        if len(d) > 1 and unicodedata.category(d[0]).startswith("L") and all(unicodedata.category(x) == "Mn" for x in d[1:]):
            result.append((cp, ord(d[0]), ord(d[1])))
    return result


def case_table(fn):
    pairs = []
    for cp in range(0x110000):
        ch = chr(cp)
        if unicodedata.category(ch) == "Cs":
            continue
        mapped = fn(ch)
        if len(mapped) == 1 and mapped != ch:
            pairs.append((cp, ord(mapped)))
    return pairs


def simple_fold(ch):
    # Simple folding: the full folding when it is one character, otherwise the lowercase mapping
    # (CaseFolding.txt gives U+1E9E the simple folding U+00DF and the full folding "ss").
    folded = ch.casefold()
    return folded if len(folded) == 1 else ch.lower()


def special_table(fn):
    pairs = []
    for cp in range(0x110000):
        ch = chr(cp)
        if unicodedata.category(ch) == "Cs":
            continue
        mapped = fn(ch)
        if len(mapped) > 1:
            pairs.append((cp, [ord(c) for c in mapped]))
    return pairs


# The decomposition tags of UnicodeData.txt, in the order of QChar::Decomposition (Canonical is 1).
TAGS = ["", "", "font", "noBreak", "initial", "medial", "final", "isolated", "circle", "super", "sub",
        "vertical", "wide", "narrow", "small", "square", "compat", "fraction"]


def raw_decompositions():
    """The one-level decomposition mappings of UnicodeData.txt, without the Hangul syllables (they are
    decomposed by formula): (code point, tag index, mapped code points)."""
    result = []
    for cp in range(0x110000):
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d:
            continue
        parts = d.split()
        tag = 1
        if parts[0].startswith("<"):
            tag = TAGS.index(parts[0][1:-1])
            parts = parts[1:]
        result.append((cp, tag, [int(x, 16) for x in parts]))
    return result


def combining_class_runs():
    runs, previous = [], None
    for cp in range(0x110000):
        ccc = unicodedata.combining(chr(cp))
        if ccc != previous:
            runs.append((cp << 8) | ccc)
            previous = ccc
    return runs


def compositions():
    """Primary composites: pairs whose canonical one-level decomposition is two code points and that
    NFC recomposes, sorted by the pair."""
    pairs = []
    for cp, tag, mapped in raw_decompositions():
        if tag == 1 and len(mapped) == 2 and unicodedata.normalize("NFC", chr(cp)) == chr(cp):
            pairs.append(((mapped[0] << 21) | mapped[1], cp))
    return sorted(pairs)


def main(path):
    out = ["// MIT License - see LICENSE", "#pragma once", "",
           "// Generated by tools/gen_unicodedata.py from the Unicode Character Database %s; do not edit." % unicodedata.unidata_version,
           "", "#include <cstdint>", "", "// The tables are laid out by the generator.", "// clang-format off", "", "namespace QtPrivate {", "namespace UnicodeData {", "",
           "// Each entry starts a run of code points with the same general category: the code point shifted",
           "// left by 5, ORed with the category in the order of QtPrivate::Unicode::Category.",
           "inline constexpr std::uint32_t categoryRuns[] = {"]
    out += wrap(["0x%x," % r for r in category_runs()])
    out += ["};", "",
            "// Letters with a canonical decomposition into a base letter and combining marks: the code",
            "// point, the base letter and the first combining mark.",
            "struct Decomposition {", "    char16_t code;", "    char16_t base;", "    char16_t mark;", "};",
            "inline constexpr Decomposition decompositions[] = {"]
    out += wrap(["{0x%x, 0x%x, 0x%x}," % d for d in decompositions()])
    out += ["};", "", "struct CaseMapping {", "    char32_t code;", "    char32_t mapped;", "};"]
    for name, fn, doc in (("lowercaseMappings", str.lower, "Simple lowercase mappings"),
                          ("uppercaseMappings", str.upper, "Simple uppercase mappings"),
                          ("titlecaseMappings", str.title, "Simple titlecase mappings"),
                          ("caseFoldings", simple_fold, "Simple case foldings")):
        out += ["// %s, sorted by code point." % doc, "inline constexpr CaseMapping %s[] = {" % name]
        out += wrap(["{0x%x, 0x%x}," % p for p in case_table(fn)])
        out += ["};", ""]
    out += ["// Full case mappings that produce more than one character (from SpecialCasing.txt and",
            "// CaseFolding.txt), such as U+00DF to \"SS\"; unused entries of mapped are 0.",
            "struct SpecialCasing {", "    char32_t code;", "    char32_t mapped[3];", "};"]
    for name, fn, doc in (("specialUppercase", str.upper, "Full uppercase mappings"),
                          ("specialLowercase", str.lower, "Full lowercase mappings"),
                          ("specialCaseFoldings", str.casefold, "Full case foldings")):
        out += ["// %s with more than one character, sorted by code point." % doc,
                "inline constexpr SpecialCasing %s[] = {" % name]
        out += wrap(["{0x%x, {%s}}," % (cp, ", ".join("0x%x" % c for c in (m + [0, 0, 0])[:3])) for cp, m in special_table(fn)])
        out += ["};", ""]
    out += ["// Runs of the canonical combining class: the first code point of a run shifted left by 8,",
            "// ORed with the class of the run.",
            "inline constexpr std::uint32_t combiningClassRuns[] = {"]
    out += wrap(["0x%x," % r for r in combining_class_runs()])
    out += ["};", ""]
    decomp = raw_decompositions()
    pool, entries = [], []
    for cp, tag, mapped in decomp:
        entries.append("{0x%x, %d, %d, %d}," % (cp, len(pool), len(mapped), tag))
        pool += mapped
    out += ["// The one-level decomposition mappings of UnicodeData.txt, sorted by code point, without the",
            "// Hangul syllables. A mapping is length code points of decompositionPool from offset; tag is",
            "// the QChar::Decomposition value (1 for a canonical mapping).",
            "struct DecompositionMapping {", "    char32_t code;", "    std::uint16_t offset;",
            "    std::uint8_t length;", "    std::uint8_t tag;", "};",
            "inline constexpr DecompositionMapping decompositionMappings[] = {"]
    out += wrap(entries)
    out += ["};", "inline constexpr char32_t decompositionPool[] = {"]
    out += wrap(["0x%x," % c for c in pool])
    out += ["};", "",
            "// Canonical compositions, sorted by pair: the first code point shifted left by 21, ORed with",
            "// the second, and the composite.",
            "struct Composition {", "    std::uint64_t pair;", "    char32_t composite;", "};",
            "inline constexpr Composition compositions[] = {"]
    out += wrap(["{0x%xull, 0x%x}," % c for c in compositions()])
    out += ["};", ""]
    out += ["} // namespace UnicodeData", "} // namespace QtPrivate", "", "// clang-format on", ""]
    with open(path, "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "src/qunicodedata_p.h")
