/*!
    \class QSocketNotifier
    \brief The QSocketNotifier class provides a way to watch activity on a file descriptor.

    A QSocketNotifier emits activated() from the event loop when a file
    descriptor becomes readable, writable or has an exceptional condition.
    The notifier does not own the descriptor and does not read or write it;
    the slot must do so, otherwise activated() fires again on the next pass.

    \code
    QSocketNotifier notifier(fd, QSocketNotifier::Read);
    QObject::connect(&notifier, &QSocketNotifier::activated, [](QSocketDescriptor fd) {
        drain(fd);
    });
    \endcode

    \differences
    The notifier is serviced by the event loop of the thread it lives in, and
    moves with the object in QObject::moveToThread(). It can be enabled and
    disabled only from that thread. Descriptors are watched with \c poll(), so
    only POSIX descriptors are supported, and the \c Exception type watches for \c POLLPRI. The type of
    the \c activated() signal's first argument is always QSocketDescriptor.

    On Zephyr the notifiers of a thread are waited for in one \c poll() if \c CONFIG_ZVFS_POLL_MAX allows,
    and in groups otherwise, which delays a socket by a few milliseconds per group. See \l{Nt on Zephyr}.
    \enddifferences

    \sa QSocketDescriptor, QEventLoop
*/

/*!
    Constructs a notifier that watches \a socket for the condition \a type.
    The notifier is enabled and has the given \a parent.
*/
QSocketNotifier::QSocketNotifier(qintptr socket, Type type, QObject *parent)
    : QObject(parent), m_fd(socket), m_type(type) {
    if (isValid())
        QtPrivate::updateNotifier(QtPrivate::objectThreadData(this), this, true);
}

/*!
    \since 6.1
    Constructs a notifier of the type \a type with the given \a parent and no socket. It is not valid and does
    nothing until setSocket() gives it one and setEnabled() enables it.

    \sa setSocket(), isValid()
*/
QSocketNotifier::QSocketNotifier(Type type, QObject *parent)
    : QObject(parent), m_fd(-1), m_type(type), m_enabled(false) {}

/*!
    \since 6.1
    Makes the notifier watch \a socket instead of its current one. The notifier is disabled as a side effect;
    enable it with setEnabled(). Call it from the thread that the notifier lives in.

    \sa socket(), isValid()
*/
void QSocketNotifier::setSocket(qintptr socket) {
    auto *td = QtPrivate::objectThreadData(this);
    if (td != QtPrivate::ThreadData::current()) {
        qWarning("QSocketNotifier: Socket notifiers cannot be changed from another thread");
        return;
    }
    if (m_enabled && isValid())
        QtPrivate::updateNotifier(td, this, false);
    QtPrivate::removeNotifier(td, this);
    m_fd = socket;
    m_enabled = false;
}

/*!
    Destroys the notifier and stops watching the descriptor. The descriptor
    is not closed.
*/
QSocketNotifier::~QSocketNotifier() {
    auto *td = QtPrivate::objectThreadData(this);
    if (m_enabled && isValid())
        QtPrivate::updateNotifier(td, this, false);
    QtPrivate::removeNotifier(td, this);
}

/*!
    Enables the notifier if \a enable is \c true; otherwise disables it. A
    disabled notifier does not emit activated(). The notifier registers itself with the event dispatcher of its
    thread while it is enabled and has a socket.

    \sa isEnabled(), QAbstractEventDispatcher::registerSocketNotifier()
*/
void QSocketNotifier::setEnabled(bool enable) {
    if (m_enabled == enable)
        return;
    auto *td = QtPrivate::objectThreadData(this);
    if (td != QtPrivate::ThreadData::current()) {
        qWarning("QSocketNotifier: Socket notifiers cannot be enabled or disabled from another thread");
        return;
    }
    m_enabled = enable;
    if (isValid())
        QtPrivate::updateNotifier(td, this, enable);
}

/*!
    \reimp
*/
bool QSocketNotifier::event(QEvent *e) {
    if (e->type() == QEvent::SockAct) {
        if (m_enabled)
            activated(QSocketDescriptor(static_cast<int>(m_fd)), m_type);
        return true;
    }
    return QObject::event(e);
}

