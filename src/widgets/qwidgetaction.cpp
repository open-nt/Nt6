#include <QtWidgets/qwidgetaction.h>

#include <algorithm>

/*!
    \class QWidgetAction
    \brief The QWidgetAction class is an action that a widget stands for in a tool bar.

    A widget action puts a widget, such as a combo box or a slider, in a QToolBar where a button would be. Give it a
    default widget, which one tool bar at a time shows:

    \code
    auto *zoom = new QWidgetAction(window);
    zoom->setDefaultWidget(new QSlider(Qt::Horizontal));
    toolBar->addAction(zoom);
    \endcode

    To show the action in several places at once, subclass it and reimplement createWidget() to make a widget for each,
    and deleteWidget() if they need more than deleting.

    \differences
    Only QToolBar asks for the widgets: a widget action in a QMenu is shown as a plain entry with its text.
    \enddifferences

    \sa QAction, QToolBar::addWidget()
*/

/*!
    Constructs a widget action with the given \a parent.
*/
QWidgetAction::QWidgetAction(QObject *parent) : QAction(parent) {}

/*!
    Destroys the action, its default widget and the widgets it made.
*/
QWidgetAction::~QWidgetAction() {
    for (const QPointer<QWidget> &w : m_created)
        delete w.data();
    delete m_default.data();
}

/*!
    Makes \a widget the default widget of the action, which the action owns. The default widget that it had is
    deleted. The default widget is shown by one tool bar at a time.

    \sa defaultWidget()
*/
void QWidgetAction::setDefaultWidget(QWidget *widget) {
    if (widget == m_default)
        return;
    delete m_default.data();
    m_default = widget;
    m_defaultInUse = false;
    if (widget) {
        widget->hide();
        widget->setParent(nullptr);
    }
}

/*!
    \fn QWidget *QWidgetAction::defaultWidget() const

    Returns the default widget, or \c nullptr.
*/

/*!
    Returns a widget for the action in \a parent: one made by createWidget(), or else the default widget if no one else
    uses it, or \c nullptr. Give it back with releaseWidget().

    \sa releaseWidget()
*/
QWidget *QWidgetAction::requestWidget(QWidget *parent) {
    if (QWidget *w = createWidget(parent)) {
        m_created.emplace_back(w);
        return w;
    }
    if (!m_default || m_defaultInUse)
        return nullptr;
    m_defaultInUse = true;
    m_default->setParent(parent);
    return m_default;
}

/*!
    Gives back \a widget, which requestWidget() returned. A widget made by createWidget() goes to deleteWidget(); the
    default widget is hidden and kept for the next request.
*/
void QWidgetAction::releaseWidget(QWidget *widget) {
    if (!widget)
        return;
    if (widget == m_default) {
        m_defaultInUse = false;
        widget->hide();
        widget->setParent(nullptr);
        return;
    }
    const auto it = std::find(m_created.begin(), m_created.end(), widget);
    if (it == m_created.end())
        return;
    m_created.erase(it);
    deleteWidget(widget);
}

/*!
    Is called by requestWidget() to make a widget in \a parent. The default implementation returns \c nullptr, so that
    the default widget is used.
*/
QWidget *QWidgetAction::createWidget(QWidget *parent) {
    (void)parent;
    return nullptr;
}

/*!
    Is called by releaseWidget() for \a widget, which createWidget() made. The default implementation deletes it.
*/
void QWidgetAction::deleteWidget(QWidget *widget) { delete widget; }

/*!
    Returns the widgets that createWidget() made and that are in use.
*/
QList<QWidget *> QWidgetAction::createdWidgets() const {
    QList<QWidget *> list;
    for (const QPointer<QWidget> &w : m_created)
        if (w)
            list.append(w.data());
    return list;
}

