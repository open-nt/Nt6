/*!
    Called when the editor \a editor of the item \a index is no longer
    needed. The base implementation deletes it when control returns to the
    event loop; a delegate that keeps its editors for reuse overrides this.

    \sa createEditor()
*/
void QAbstractItemDelegate::destroyEditor(QWidget *editor, const QModelIndex &index) const {
    static_cast<void>(index);
    if (editor)
        editor->deleteLater();
}

