#include <QtWebSockets/qmaskgenerator.h>

/*!
    \class QMaskGenerator
    \brief The QMaskGenerator class is the base of generators of the masking keys that WebSocket clients use.
    \since 5.3

    A WebSocket client masks each frame it sends with a 32-bit key, so that
    a script cannot place chosen bytes on the wire and confuse proxies.
    QWebSocket uses the system's random number generator by default. A
    subclass can replace it, for example to make tests repeatable; pass it to
    QWebSocket::setMaskGenerator().

    \differences
    None.
    \enddifferences

    \sa QWebSocket::setMaskGenerator()
*/

/*!
    Constructs a mask generator with the given \a parent.
*/
QMaskGenerator::QMaskGenerator(QObject *parent) : QObject(parent) {}

/*!
    Destroys the mask generator.
*/
QMaskGenerator::~QMaskGenerator() = default;

