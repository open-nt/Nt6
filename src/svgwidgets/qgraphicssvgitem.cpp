#include <QtSvgWidgets/qgraphicssvgitem.h>

#include <QtGui/qpainter.h>
#include <QtSvg/qsvgrenderer.h>

/*!
    \class QGraphicsSvgItem
    \inmodule NtSvgWidgets
    \brief The QGraphicsSvgItem class shows an SVG drawing, or one element of it, in a QGraphicsScene.

    The item is as large as the drawing's default size, or as the bounds of elementId() when one is set:

    \code
    auto *dial = new QGraphicsSvgItem(QStringLiteral(":/images/dial.svg"));
    scene.addItem(dial);
    auto *needle = new QGraphicsSvgItem;
    needle->setSharedRenderer(dial->renderer());
    needle->setElementId(QStringLiteral("needle"));
    scene.addItem(needle);
    \endcode

    \differences
    The drawing is rendered each time the item is painted; caching and maximumCacheSize() are stored but
    have no effect.
    \enddifferences

    \sa QSvgRenderer, QGraphicsScene
*/

/*!
    Constructs an empty item, a child of \a parentItem.
*/
QGraphicsSvgItem::QGraphicsSvgItem(QGraphicsItem *parentItem) : QGraphicsObject(parentItem) {
    setSharedRenderer(new QSvgRenderer(this));
    m_shared = false;
}

/*!
    Constructs an item showing the SVG file \a fileName, a child of \a parentItem.
*/
QGraphicsSvgItem::QGraphicsSvgItem(const QString &fileName, QGraphicsItem *parentItem) : QGraphicsObject(parentItem) {
    setSharedRenderer(new QSvgRenderer(fileName, this));
    m_shared = false;
}

/*!
    Destroys the item, and its renderer unless it was set with setSharedRenderer().
*/
QGraphicsSvgItem::~QGraphicsSvgItem() = default;

/*!
    Makes the item draw with \a renderer, which it does not take ownership of. Several items can share one
    renderer, each showing a different element.
*/
void QGraphicsSvgItem::setSharedRenderer(QSvgRenderer *renderer) {
    if (renderer == m_renderer)
        return;
    disconnect(m_repaint);
    if (m_renderer && !m_shared && m_renderer->parent() == this)
        delete m_renderer;
    m_renderer = renderer;
    m_shared = true;
    if (m_renderer)
        m_repaint = connect(m_renderer, &QSvgRenderer::repaintNeeded, this, [this] { updateBounds(); });
    updateBounds();
}

/*!
    Returns the renderer the item draws with.
*/
QSvgRenderer *QGraphicsSvgItem::renderer() const { return m_renderer; }

/*!
    Makes the item show only the element whose id is \a id; an empty \a id shows the whole drawing.
*/
void QGraphicsSvgItem::setElementId(const QString &id) {
    m_elementId = id;
    updateBounds();
}

/*!
    Returns the id of the element the item shows, or an empty string for the whole drawing.
*/
QString QGraphicsSvgItem::elementId() const { return m_elementId; }

/*!
    Sets whether the rendering is cached to \a enabled. Nt stores the setting only.
*/
void QGraphicsSvgItem::setCachingEnabled(bool enabled) { m_caching = enabled; }

/*!
    Returns the setting made with setCachingEnabled().
*/
bool QGraphicsSvgItem::isCachingEnabled() const { return m_caching; }

/*!
    Sets the largest cached rendering to \a size. Nt stores the setting only.
*/
void QGraphicsSvgItem::setMaximumCacheSize(const QSize &size) { m_maxCache = size; }

/*!
    Returns the size set with setMaximumCacheSize(); 1024 by 768 by default.
*/
QSize QGraphicsSvgItem::maximumCacheSize() const { return m_maxCache; }

void QGraphicsSvgItem::updateBounds() {
    QRectF bounds;
    if (m_renderer) {
        if (m_elementId.isEmpty())
            bounds = QRectF(QPointF(0, 0), QSizeF(m_renderer->defaultSize()));
        else
            bounds = QRectF(QPointF(0, 0), m_renderer->boundsOnElement(m_elementId).size());
    }
    if (bounds != m_bounds) {
        prepareGeometryChange();
        m_bounds = bounds;
    }
    update();
}

/*!
    \reimp
*/
QRectF QGraphicsSvgItem::boundingRect() const { return m_bounds; }

/*!
    \reimp
*/
void QGraphicsSvgItem::paint(QPainter *painter, const QStyleOptionGraphicsItem *option, QWidget *widget) {
    Q_UNUSED(option);
    Q_UNUSED(widget);
    if (!m_renderer || !m_renderer->isValid() || m_bounds.isEmpty())
        return;
    if (m_elementId.isEmpty())
        m_renderer->render(painter, m_bounds);
    else
        m_renderer->render(painter, m_elementId, m_bounds);
}

/*!
    \reimp
*/
int QGraphicsSvgItem::type() const { return Type; }

