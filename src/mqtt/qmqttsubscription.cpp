#include <QtMqtt/qmqttclient.h>
#include <QtMqtt/qmqttsubscription.h>

/*!
    \class QMqttSubscription
    \brief The QMqttSubscription class receives the messages of the topics that a filter matches.
    \since 6.0

    QMqttClient::subscribe() makes a subscription, which the client owns. It is \c SubscriptionPending
    until the broker acknowledges it, and then \c Subscribed, or \c Error if the broker refused it.
    Each message whose topic the filter matches arrives with messageReceived().

    \differences
    The subscription stays an object of the client after it is unsubscribed, until the client is
    destroyed; subscribing to the same filter again makes a new one. There is no reason code, no
    subscription identifier and no user properties, which come with MQTT 5.
    \enddifferences

    \sa QMqttClient::subscribe()
*/

/*!
    \enum QMqttSubscription::SubscriptionState

    The state of a subscription.

    \value Unsubscribed Not subscribed: unsubscribed, or the client disconnected.
    \value SubscriptionPending The broker has not yet acknowledged the subscription.
    \value Subscribed The broker acknowledged the subscription.
    \value UnsubscriptionPending The broker has not yet acknowledged the unsubscription.
    \value Error The broker refused the subscription.
*/

QMqttSubscription::QMqttSubscription(QObject *parent) : QObject(parent) {}

/*!
    Destroys the subscription. The client owns it; it is not unsubscribed.
*/
QMqttSubscription::~QMqttSubscription() = default;

/*!
    Returns the state of the subscription.
*/
QMqttSubscription::SubscriptionState QMqttSubscription::state() const { return m_state; }

/*!
    Returns the topic filter of the subscription.
*/
QMqttTopicFilter QMqttSubscription::topic() const { return m_topic; }

/*!
    Returns the QoS that the broker granted, which can be lower than the one asked for.
*/
quint8 QMqttSubscription::qos() const { return m_qos; }

/*!
    Returns whether the filter is a shared subscription, \c{$share/<name>/<filter>}.
*/
bool QMqttSubscription::isSharedSubscription() const { return !m_topic.sharedSubscriptionName().isEmpty(); }

/*!
    Returns the name of the shared subscription, or an empty string.
*/
QString QMqttSubscription::sharedSubscriptionName() const { return m_topic.sharedSubscriptionName(); }

/*!
    Unsubscribes from the topic filter.

    \sa QMqttClient::unsubscribe()
*/
void QMqttSubscription::unsubscribe() {
    if (m_client)
        m_client->unsubscribe(m_topic);
}

void QMqttSubscription::setState(SubscriptionState state) {
    if (m_state == state)
        return;
    m_state = state;
    stateChanged(state);
}

void QMqttSubscription::setQos(quint8 qos) {
    if (m_qos == qos)
        return;
    m_qos = qos;
    qosChanged(qos);
}

/*!
    \fn void QMqttSubscription::messageReceived(QMqttMessage msg)

    This signal is emitted for each message \a msg whose topic the filter matches.
*/

/*!
    \fn void QMqttSubscription::stateChanged(QMqttSubscription::SubscriptionState state)

    This signal is emitted when the state changes to \a state.
*/

/*!
    \fn void QMqttSubscription::qosChanged(quint8 qos)

    This signal is emitted when the granted QoS changes to \a qos.
*/

