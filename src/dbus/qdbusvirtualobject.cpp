#include <QtDBus/qdbusvirtualobject.h>

/*!
    \class QDBusVirtualObject
    \brief The QDBusVirtualObject class is used to handle several D-Bus paths with one class.

    Subclass it and implement introspect() and handleMessage(), then register it with
    QDBusConnection::registerVirtualObject(). With \c QDBusConnection::SubPath it receives the
    calls to every path below its own as well, which suits a tree of objects that exist only
    as data:

    \code
    class Files : public QDBusVirtualObject {
    public:
        QString introspect(const QString &) const override { return QString(); }
        bool handleMessage(const QDBusMessage &m, const QDBusConnection &c) override {
            if (m.member() != "Size")
                return false;
            c.send(m.createReply(QFileInfo(m.path().mid(6)).size()));
            return true;
        }
    };
    \endcode

    \differences
    None.
    \enddifferences

    \sa QDBusConnection::registerVirtualObject()
*/

/*!
    Constructs a virtual object with the given \a parent.
*/
QDBusVirtualObject::QDBusVirtualObject(QObject *parent) : QObject(parent) {}

/*!
    Destroys the virtual object. It is unregistered.
*/
QDBusVirtualObject::~QDBusVirtualObject() = default;

