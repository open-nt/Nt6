/*!
    \since 6.0

    Returns the input method of the platform, which the application owns.
*/
QInputMethod *QGuiApplication::inputMethod() {
    static QPointer<QInputMethod> method; // a child of the application, made again for a new one
    if (!method)
        method = new QInputMethod(qGuiApp);
    return method.data();
}

