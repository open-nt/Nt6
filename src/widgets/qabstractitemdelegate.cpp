/*!
    \class QAbstractItemDelegate
    \brief The QAbstractItemDelegate class is used to display and edit data items from a model.

    A view does not draw its items itself: it asks its delegate, for each
    item, to paint() it and to tell its sizeHint(). The delegate also makes
    the widget that an item is edited with: createEditor() makes it,
    setEditorData() fills it from the model, updateEditorGeometry() places
    it over the item, and setModelData() writes what the user entered back
    to the model. When the user is done, the delegate emits commitData()
    and closeEditor().

    Subclass QStyledItemDelegate, which does all this for the usual kinds
    of data, to change how some items look or are edited; subclass this
    class to do it all from scratch.

    \differences
    There is no \c helpEvent(): the view shows the tool tips of its items.
    \enddifferences

    \sa QStyledItemDelegate, QAbstractItemView
*/

