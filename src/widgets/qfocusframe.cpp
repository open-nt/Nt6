#include <QtWidgets/qfocusframe.h>

#include "qwidget_p.h"

#include <QtCore/qcoreevent.h>
#include <QtGui/qpainter.h>

namespace {

constexpr int kMargin = 2; // how far the frame is outside the widget

} // namespace

/*!
    \class QFocusFrame
    \brief The QFocusFrame class draws a frame around a widget, outside it.

    A focus frame follows a widget: it sits around it, in the parent of the widget, and moves, resizes, shows and hides
    with it. It is meant for showing the focus around a widget that does not draw it itself:

    \code
    auto *frame = new QFocusFrame(window);
    frame->setWidget(canvas);
    \endcode

    The frame lets the mouse through to the widgets under it.

    \differences
    The frame is drawn by Nt in the highlight color, not by the style, and it follows the widget it was given rather
    than the focus.
    \enddifferences

    \sa QRubberBand
*/

/*!
    Constructs a focus frame with the given \a parent, which follows no widget.
*/
QFocusFrame::QFocusFrame(QWidget *parent) : QWidget(parent) {
    QtPrivate::WidgetAccess::data(this).mouseTransparent = true;
    hide();
}

/*!
    Destroys the focus frame.
*/
QFocusFrame::~QFocusFrame() {
    if (m_widget)
        m_widget->removeEventFilter(this);
}

/*!
    Makes the frame follow \a widget, or no widget if it is \c nullptr or a window. The frame becomes a child of the
    parent of the widget.

    \sa widget()
*/
void QFocusFrame::setWidget(QWidget *widget) {
    if (m_widget)
        m_widget->removeEventFilter(this);
    m_widget = widget && !widget->isWindow() ? widget : nullptr;
    if (!m_widget) {
        hide();
        return;
    }
    if (parentWidget() != m_widget->parentWidget())
        setParent(m_widget->parentWidget());
    m_widget->installEventFilter(this);
    follow();
}

/*!
    \fn QWidget *QFocusFrame::widget() const

    Returns the widget that the frame follows, or \c nullptr.
*/

void QFocusFrame::follow() {
    if (!m_widget)
        return;
    setGeometry(m_widget->geometry().adjusted(-kMargin, -kMargin, kMargin, kMargin));
    setVisible(!m_widget->isHidden());
    raise();
}

/*!
    \reimp

    Follows the moves, resizes, shows and hides of the widget.
*/
bool QFocusFrame::eventFilter(QObject *watched, QEvent *event) {
    if (watched == m_widget) {
        switch (event->type()) {
        case QEvent::Move:
        case QEvent::Resize:
        case QEvent::Show:
        case QEvent::Hide:
            follow();
            break;
        case QEvent::ParentChange:
            setWidget(m_widget);
            break;
        default:
            break;
        }
    }
    return false;
}

/*!
    \reimp
*/
void QFocusFrame::paintEvent(QPaintEvent *event) {
    (void)event;
    QPainter painter(this);
    painter.setPen(palette().color(QPalette::Active, QPalette::Highlight));
    painter.setBrush(Qt::NoBrush);
    painter.drawRect(rect().adjusted(0, 0, -1, -1));
    painter.drawRect(rect().adjusted(1, 1, -2, -2));
}

