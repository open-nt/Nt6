/*!
    \class QRadioButton
    \brief The QRadioButton class provides a radio button with a text label.

    Radio buttons that have the same parent widget form a group in which only one is checked: checking one
    unchecks the others. Put the buttons of a group in a QGroupBox, or in a widget of their own, to have
    several groups in a window. The arrow keys move the choice from one button of the group to the next.

    \code
    QGroupBox *size = new QGroupBox("Size", window);
    QRadioButton *small = new QRadioButton("Small", size);
    QRadioButton *large = new QRadioButton("Large", size);
    small->setChecked(true);
    \endcode

    Radio buttons: not chosen, chosen, with the keyboard focus, and disabled.

    \image widgets/qradiobutton.png QRadioButton in the light color scheme

    \differences
    Groups are made by the parent widget only; there is no \c QButtonGroup.
    \enddifferences

    \sa QAbstractButton, QCheckBox, QGroupBox
*/

/*!
    Constructs a radio button with no text and the given \a parent.
*/
QRadioButton::QRadioButton(QWidget *parent) : QAbstractButton(parent) {
    setCheckable(true);
    setAutoExclusive(true);
    setSizePolicy(QSizePolicy::Minimum, QSizePolicy::Fixed);
}

/*!
    Constructs a radio button that shows \a text, with the given \a parent.
*/
QRadioButton::QRadioButton(const QString &text, QWidget *parent) : QRadioButton(parent) { setText(text); }

/*!
    Destroys the radio button.
*/
QRadioButton::~QRadioButton() = default;

/*!
    \reimp
*/
QSize QRadioButton::sizeHint() const {
    const QSize text = fontMetrics().size(Qt::TextSingleLine, this->text());
    QStyleOptionButton option;
    option.initFrom(this);
    option.text = this->text();
    return style()->sizeFromContents(QStyle::CT_RadioButton, &option, text, this);
}

/*!
    \reimp
*/
bool QRadioButton::hitButton(const QPoint &pos) const {
    const QSize hint = sizeHint();
    return QRect(0, 0, std::min(width(), hint.width()), height()).contains(pos);
}

/*!
    \reimp
*/
void QRadioButton::keyPressEvent(QKeyEvent *event) {
    const int key = event->key();
    if (key == Qt::Key_Up || key == Qt::Key_Left || key == Qt::Key_Down || key == Qt::Key_Right) {
        // Move the choice to the previous or next radio button of the group, in the order they were created.
        // The buttons of a button group go together; otherwise the radio buttons of the same parent do.
        std::vector<QRadioButton *> group;
        const auto consider = [&](QObject *object) {
            auto *other = dynamic_cast<QRadioButton *>(object);
            if (other && other->group() == this->group() && other->isEnabled() && !other->isHidden())
                group.push_back(other);
        };
        if (this->group()) {
            for (QAbstractButton *button : this->group()->buttons())
                consider(button);
        } else if (parentWidget()) {
            for (QObject *child : parentWidget()->children())
                consider(child);
        }
        const auto it = std::find(group.begin(), group.end(), this);
        if (it != group.end() && group.size() > 1) {
            const std::size_t at = static_cast<std::size_t>(it - group.begin());
            const bool forward = key == Qt::Key_Down || key == Qt::Key_Right;
            QRadioButton *next = group[forward ? (at + 1) % group.size() : (at + group.size() - 1) % group.size()];
            next->setFocus();
            next->click();
        }
        event->accept();
        return;
    }
    QAbstractButton::keyPressEvent(event);
}

/*!
    \reimp
*/
void QRadioButton::paintEvent(QPaintEvent *event) {
    (void)event;
    QPainter painter(this);
    painter.setFont(font());
    QStyleOptionButton option;
    option.initFrom(this);
    option.text = text();
    option.state |= isDown() ? QStyle::State_Sunken : QStyle::State_Raised;
    option.state |= isChecked() ? QStyle::State_On : QStyle::State_Off;
    style()->drawControl(QStyle::CE_RadioButton, &option, &painter, this);
}

